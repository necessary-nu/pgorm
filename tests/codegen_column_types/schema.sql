CREATE TYPE grade AS ENUM ('low', 'high');
CREATE TYPE textrange AS RANGE (SUBTYPE = text);
CREATE TABLE specimen (
    id integer PRIMARY KEY,
    code varchar(3) NOT NULL,
    title character varying(255),
    note varchar NOT NULL,
    initials char(2) NOT NULL,
    flag char NOT NULL,
    pad bpchar NOT NULL,
    body text NOT NULL,
    codes varchar(3)[] NOT NULL,
    marks character(4)[],
    notes varchar[] NOT NULL,
    price numeric(10, 2) NOT NULL,
    whole numeric(6) NOT NULL,
    amount numeric NOT NULL,
    prices numeric(8, 3)[] NOT NULL,
    cost money,
    small smallint NOT NULL,
    big bigint NOT NULL,
    ratio real NOT NULL,
    weight double precision NOT NULL,
    doc json NOT NULL,
    data jsonb NOT NULL,
    blob bytea NOT NULL,
    ok boolean NOT NULL,
    uid uuid NOT NULL,
    day date NOT NULL,
    clock time NOT NULL,
    seen timestamp NOT NULL,
    stamped timestamptz NOT NULL,
    wait interval NOT NULL,
    months interval YEAR TO MONTH NOT NULL,
    span int4range NOT NULL,
    days datemultirange NOT NULL,
    level grade NOT NULL,
    letters textrange NOT NULL
);

"""A declared model's hooks, against a live server: they run around the
record writes of Model.active(values), sync or async, a before_* hook's
error refusing the write before anything is sent and an after_* hook's
arriving once the row is written, while the statement builders run none."""

import os
import unittest

import pgorm as p

SCHEMA = "python_hooks"
DDL = [
    f"CREATE SCHEMA {SCHEMA}",
    f"CREATE TABLE {SCHEMA}.special (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, note text NOT NULL)",
]

COLUMNS = {
    "id": p.Column("i32", primary_key=True, default=True),
    "name": p.Column("text"),
    "note": p.Column("text"),
}


class Declaration(unittest.TestCase):
    # [spec:pgorm:req:bindings.model-hooks/test]    the hooks a model takes, and what describe() says of them
    def test_hooks_are_declared_and_described(self):
        special = p.Model("special", COLUMNS, schema=SCHEMA, hooks={"before_save": lambda values, insert: values})
        self.assertEqual(special.describe()["hooks"], ["before_save"])
        self.assertEqual(special.as_("s").describe()["hooks"], ["before_save"])
        self.assertEqual(p.Model("special", COLUMNS, schema=SCHEMA).describe()["hooks"], [])
        with self.assertRaisesRegex(TypeError, "'before_insert' is no model hook"):
            p.Model("special", COLUMNS, hooks={"before_insert": print})  # type: ignore[typeddict-unknown-key]
        with self.assertRaisesRegex(TypeError, "before_save hook is a function"):
            p.Model("special", COLUMNS, hooks={"before_save": "nope"})  # type: ignore[typeddict-item]
        with self.assertRaises(TypeError):
            p.Model("special", COLUMNS, hooks=[])  # type: ignore[arg-type]
        with self.assertRaisesRegex(p.ConstructionError, "no field 'colour'"):
            special.active({"colour": "red"})
        with self.assertRaises(p.ConstructionError):
            bool(special.active({}))


class RecordWrites(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.pool = p.Pool(os.environ["PGORM_TEST_DSN"], max_size=2)
        for statement in DDL:
            await self.pool.execute(p.RawSQL(statement))
        self.calls = []

    async def asyncTearDown(self):
        await self.pool.execute(p.RawSQL(f"DROP SCHEMA {SCHEMA} CASCADE"))
        await self.pool.close()

    def hooked(self):
        calls = self.calls

        def before_save(values, insert):
            calls.append(("before_save", dict(values), insert))
            if not values.get("name", "x"):
                raise ValueError("a special needs a name")
            return {"note": "Ask at the counter", **values}

        async def after_save(record, insert):
            calls.append(("after_save", record["name"], insert))
            return record

        async def before_delete(values):
            calls.append(("before_delete", dict(values)))
            return values

        def after_delete(values):
            calls.append(("after_delete", dict(values)))

        return p.Model(
            "special", COLUMNS, schema=SCHEMA,
            hooks={"before_save": before_save, "after_save": after_save,
                   "before_delete": before_delete, "after_delete": after_delete},
        )

    # [spec:pgorm:req:bindings.model-hooks/test]    insert, update and delete run the hooks around the write
    async def test_record_writes_run_the_hooks(self):
        special = self.hooked()
        saved = await special.active({"name": "Saturday buns"}).insert(self.pool)
        self.assertEqual((saved["name"], saved["note"]), ("Saturday buns", "Ask at the counter"))
        updated = await special.active({"id": saved["id"], "name": "Sunday buns"}).update(self.pool)
        self.assertEqual((updated["name"], updated["note"]), ("Sunday buns", "Ask at the counter"))
        deleted = await special.active({"id": saved["id"]}).delete(self.pool)
        self.assertEqual(deleted, 1)
        self.assertEqual(
            [call[0] for call in self.calls],
            ["before_save", "after_save", "before_save", "after_save", "before_delete", "after_delete"],
        )
        self.assertEqual((self.calls[0][2], self.calls[2][2]), (True, False))

    # [spec:pgorm:req:bindings.model-hooks/test]    a before hook's error refuses the write; an after hook's comes after it
    async def test_refusals_and_after_errors(self):
        special = self.hooked()
        with self.assertRaisesRegex(ValueError, "a special needs a name"):
            await special.active({"name": ""}).insert(self.pool)
        self.assertEqual((await self.pool.one(p.RawSQL(f"SELECT count(*) AS n FROM {SCHEMA}.special")))["n"], 0)

        def failing(record, insert):
            raise RuntimeError("after the write")

        loud = p.Model("special", COLUMNS, schema=SCHEMA, hooks={"after_save": failing})
        with self.assertRaisesRegex(RuntimeError, "after the write"):
            await loud.active({"name": "kept", "note": "n"}).insert(self.pool)
        self.assertEqual((await self.pool.one(p.RawSQL(f"SELECT count(*) AS n FROM {SCHEMA}.special")))["n"], 1)

        bad = p.Model("special", COLUMNS, schema=SCHEMA, hooks={"before_save": lambda values, insert: None})
        with self.assertRaisesRegex(TypeError, "gives the values to write"):
            await bad.active({"name": "x", "note": "n"}).insert(self.pool)
        with self.assertRaisesRegex(p.DecodeError, "no special row has the key"):
            await special.active({"id": 999, "name": "nobody"}).update(self.pool)
        with self.assertRaisesRegex(p.ConstructionError, "needs its key"):
            await special.active({"name": "no key"}).delete(self.pool)
        keyless = p.Model("special", {"name": p.Column("text"), "note": p.Column("text")}, schema=SCHEMA)
        with self.assertRaisesRegex(p.ConstructionError, "declares no primary key"):
            await keyless.active({"name": "x"}).update(self.pool)

    # [spec:pgorm:req:bindings.model-hooks/test]    the statement builders run no hook
    async def test_statement_builders_run_no_hooks(self):
        special = self.hooked()
        await special.insert({"name": "plain", "note": "n"}).execute(self.pool)
        await special.update({"note": "m"}).all_rows().execute(self.pool)
        await special.delete().all_rows().execute(self.pool)
        self.assertEqual(self.calls, [])


if __name__ == "__main__":
    unittest.main()

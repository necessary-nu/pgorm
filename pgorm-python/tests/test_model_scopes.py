"""Declared models held to scopes, as Rust's scoped entities are: every
statement on a scoped model starts from a ``_for`` form given a context
holding its scopes, which it is held to, and every statement built without
one, or under a context missing a scope, is refused as it is built."""

from dataclasses import dataclass
import os
import unittest

import pgorm as p
from pgorm import pipeline as pl

SCHEMA = "python_scopes"


class CompanyId(p.Scope[int]):
    pass


class UserId(p.Scope[int]):
    pass


@dataclass(frozen=True)
class Member(p.ScopeContext):
    company: CompanyId
    user: UserId


@dataclass(frozen=True)
class CompanyAdmin(p.ScopeContext):
    company: CompanyId
    users: p.Every[UserId]


Company = p.Model(
    "company",
    {"id": p.Column("i64", primary_key=True, scope=CompanyId), "name": p.Column("text")},
    schema=SCHEMA,
)
Note = p.Model(
    "note",
    {
        "id": p.Column("i64", primary_key=True, generated="by_default"),
        "company_id": p.Column("i64", scope=CompanyId),
        "author_id": p.Column("i64", scope=UserId),
        "body": p.Column("text"),
    },
    schema=SCHEMA,
)
Tag = p.Model(
    "tag",
    {"id": p.Column("i64", primary_key=True), "note_id": p.Column("i64"), "label": p.Column("text")},
    schema=SCHEMA,
)
company_notes = Company.has_many(Note, from_="id", to="company_id")
note_tags = Note.has_many(Tag, from_="id", to="note_id")
tag_note = Tag.belongs_to(Note, from_="note_id", to="id")
note_company = Note.belongs_to(Company, from_="company_id", to="id")
labelled = Note.has_many(Tag, from_="id", to="note_id", on_condition=lambda note, tag: tag.col("label") != "")
Pin = p.Model("pin", {"id": p.Column("i64", primary_key=True), "note_id": p.Column("i64", nullable=True)})

ADA = Member(CompanyId(1), UserId(10))
ADMIN = CompanyAdmin(CompanyId(1), p.Every(UserId))
NOTE = 'SELECT "note"."id", "note"."company_id", "note"."author_id", "note"."body" FROM "python_scopes"."note"'
NO_CONTEXT = (
    "`note` is scoped by `CompanyId` and `UserId`, which a statement taking no context does "
    "not hold: a statement on `note` starts from a `_for` form, given a context holding its "
    "scopes first: `find_for(cx)`, `insert_for(cx, values)`, `update_for(cx, values)`"
)

DDL = [
    f"CREATE SCHEMA {SCHEMA}",
    f"CREATE TABLE {SCHEMA}.company (id int8 PRIMARY KEY, name text NOT NULL)",
    f"""CREATE TABLE {SCHEMA}.note (
        id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        company_id int8 NOT NULL REFERENCES {SCHEMA}.company,
        author_id int8 NOT NULL, body text NOT NULL
    )""",
    f"CREATE TABLE {SCHEMA}.tag (id int8 PRIMARY KEY, note_id int8 NOT NULL, label text NOT NULL)",
]


class Construction(unittest.TestCase):
    # [spec:pgorm:req:bindings.scopes/test]    a read ANDs each scope its context holds one value of into its WHERE
    # [spec:pgorm:req:python.scopes/test]    a scope is a Scope subclass, a value a context of itself, a ScopeContext's fields its scopes
    def test_a_read_is_held_to_its_context(self):
        self.assertEqual(Note.scopes, ("CompanyId", "UserId"))
        self.assertEqual(
            Note.find_for(ADA).inspect().sql,
            f'{NOTE} WHERE "note"."company_id" = $1 AND "note"."author_id" = $2',
        )
        self.assertEqual(Note.find_for(ADMIN).inspect().sql, f'{NOTE} WHERE "note"."company_id" = $1')
        self.assertEqual(
            Company.find_by_key_for(CompanyId(1), {"id": 1}).inspect().sql,
            'SELECT "company"."id", "company"."name" FROM "python_scopes"."company" '
            'WHERE "company"."id" = $1 AND "company"."id" = $2',
        )
        self.assertEqual(
            Note.as_("n").select_for(ADA, "body").inspect().sql,
            'SELECT "n"."body" FROM "python_scopes"."note" AS "n" WHERE "n"."company_id" = $1 '
            'AND "n"."author_id" = $2',
        )
        self.assertEqual(Tag.find_for(ADA).inspect().sql, Tag.find().inspect().sql)
        self.assertEqual(CompanyId(1), CompanyId(1))
        self.assertNotEqual(CompanyId(1), UserId(1))
        self.assertEqual(repr(ADMIN.users), "Every(UserId)")

    # [spec:pgorm:req:bindings.scopes/test]    every form taking no context, and a context missing a scope, is refused as the statement is built
    def test_statements_without_scopes_are_refused(self):
        refused = [
            lambda: Note.find(),
            lambda: Note.select("body"),
            lambda: Note.find_by_key({"id": 1}),
            lambda: Note.insert({"body": "x"}),
            lambda: Note.insert_many([{"body": "x"}]),
            lambda: Note.update({"body": "x"}),
            lambda: Note.delete(),
            lambda: Note.graph(),
            lambda: Tag.graph().join_one(tag_note),
            lambda: tag_note.find({"note_id": 1}),
            lambda: labelled.find({"id": 1}),
            lambda: Tag.linked(tag_note, note_tags).find_linked(),
            lambda: Note.insert_for(ADA, {"body": "x"}).add({"body": "y"}),
            lambda: pl.from_(Note),
            lambda: pl.from_(Tag).join(Note, pl.col(Tag, "note_id") == pl.col(Note, "id")),
        ]
        for build in refused:
            with self.subTest(build=build), self.assertRaises(p.ConstructionError) as raised:
                build()
            self.assertIn("`note` is scoped by `CompanyId` and `UserId`, which", str(raised.exception))
        joined = [
            lambda: Company.find_for(ADA).join(company_notes),
            lambda: Tag.find_for(ADMIN).join_rev(note_tags),
            lambda: Tag.update({"label": "x"}).from_(Note),
            lambda: Tag.delete().using(Note),
        ]
        for build in joined:
            with self.subTest(build=build), self.assertRaises(p.ConstructionError) as raised:
                build()
            self.assertIn("join it with a form taking the statement's context", str(raised.exception))
        with self.assertRaises(p.ConstructionError) as raised:
            Note.find()
        self.assertEqual(str(raised.exception), NO_CONTEXT)
        with self.assertRaises(p.ConstructionError) as raised:
            Note.find_for(CompanyId(1))
        self.assertEqual(
            str(raised.exception),
            "`note` is scoped by `CompanyId` and `UserId`, which `CompanyId` does not hold",
        )
        with self.assertRaises(p.ConstructionError) as raised:
            Company.find_for(ADA).join(company_notes)
        self.assertEqual(
            str(raised.exception),
            "`note` is scoped by `CompanyId` and `UserId`; join it with a form taking the "
            "statement's context, such as `join_for`",
        )

    # [spec:pgorm:req:python.scopes/test]    a context of another type, an Every of no scope and a Scope itself are TypeErrors
    def test_contexts_are_scopes_or_everys(self):
        for context in (1, {"company": CompanyId(1)}, None, CompanyId):
            with self.subTest(context=context), self.assertRaises(TypeError):
                Note.find_for(context)
        with self.assertRaises(TypeError):
            p.Every(int)
        with self.assertRaises(TypeError):
            p.Scope(1)

        @dataclass(frozen=True)
        class Twice(p.ScopeContext):
            author: UserId
            editor: UserId

        with self.assertRaises(p.ConstructionError) as raised:
            Note.find_for(Twice(UserId(1), UserId(2)))
        self.assertIn("`Twice` holds `UserId` twice", str(raised.exception))

        @dataclass(frozen=True)
        class Loose(p.ScopeContext):
            company: int

        with self.assertRaises(TypeError):
            Note.find_for(Loose(1))

    # [spec:pgorm:req:bindings.scopes/test]    a scope column is one value of its row: nullable, array and generated ones are refused, and one scope is one column
    def test_scope_columns_declare_as_rust_does(self):
        for options in ({"nullable": True}, {"array": True}, {"generated": "always"}):
            with self.subTest(options=options), self.assertRaises(p.ConstructionError):
                p.Column("i64", scope=UserId, **options)
        with self.assertRaises(TypeError):
            p.Column("i64", scope=int)
        with self.assertRaises(p.ConstructionError):
            p.Model("pair", {
                "author": p.Column("i64", scope=UserId),
                "editor": p.Column("i64", scope=UserId),
            })
        with self.assertRaises(p.ConstructionError) as raised:
            p.OneOf("pinned", Pin, {"note": ("note_id", Note)})
        self.assertIn("is scoped by CompanyId, UserId", str(raised.exception))

    # [spec:pgorm:req:bindings.scopes/test]    joins, graph slots and hops, and a relation's finds AND the joined table's scopes into its ON
    def test_joins_hold_the_joined_tables_scopes(self):
        joined = Company.find_for(ADA).join_for(ADA, company_notes).inspect().sql
        self.assertEqual(
            joined,
            'SELECT "company"."id", "company"."name" FROM "python_scopes"."company" '
            'INNER JOIN "python_scopes"."note" ON "company"."id" = "note"."company_id" '
            'AND ("note"."company_id" = $1 AND "note"."author_id" = $2) WHERE "company"."id" = $3',
        )
        graph = Company.graph_for(ADMIN).join_maybe(company_notes, alias="n").inspect().sql
        self.assertIn('LEFT JOIN "python_scopes"."note" AS "n" ON "company"."id" = "n"."company_id" AND "n"."company_id" = $1 ', graph)
        self.assertIn('WHERE "company"."id" = $2', graph)
        reverse = Tag.find_for(ADA).join_rev_for(ADA, note_tags).inspect().sql
        self.assertIn('ON "note"."id" = "tag"."note_id" AND ("note"."company_id" = $1', reverse)
        found = tag_note.find_for(ADA, {"note_id": 1}).inspect().sql
        self.assertEqual(found, f'{NOTE} WHERE "note"."company_id" = $1 AND "note"."author_id" = $2 AND "note"."id" = $3')
        linked = Company.linked(company_notes, note_tags).find_linked_for(ADA).inspect().sql
        self.assertIn('"r0"."company_id" = $1 AND "r0"."author_id" = $2', linked)
        self.assertIn('"r1"."id" = $3', linked)

    # [spec:pgorm:req:bindings.scopes/test]    an insert fills the scope columns its row leaves out, and refuses another value or an unset column under every value
    def test_inserts_fill_and_refuse_their_rows(self):
        self.assertEqual(
            Note.insert_for(ADA, {"body": "x"}).inspect().sql,
            'INSERT INTO "python_scopes"."note" ("company_id", "author_id", "body") VALUES ($1, $2, $3)',
        )
        self.assertEqual(
            Note.insert_for(ADA, {"body": "x", "author_id": 10}).inspect().params,
            Note.insert_for(ADA, {"body": "x"}).inspect().params,
        )
        refusals = [
            (lambda: Note.insert_for(ADA, {"body": "x", "company_id": 2}),
             "the row sets `note`.`company_id` to a value outside the context's `CompanyId`"),
            (lambda: Note.insert_for(ADA, {"body": "x", "company_id": p.literal(1)}),
             "the row sets `note`.`company_id` to a value outside the context's `CompanyId`"),
            (lambda: Note.insert_for(ADMIN, {"body": "x"}),
             "the context holds every `UserId`, so the row sets `note`.`author_id` itself, and it is not set"),
            (lambda: Note.insert_many_for(ADA, [{"body": "x"}, {"body": "y", "author_id": 11}]),
             "the row sets `note`.`author_id` to a value outside the context's `UserId`"),
            (lambda: Note.insert_for(ADA, {"body": "x"}).add_for(ADMIN, {"body": "y"}),
             "the context holds every `UserId`"),
            (lambda: Note.insert_for(ADA, {"body": "x"}).on_conflict(p.Conflict.on("id").update("author_id")),
             "`note`.`author_id` is written when its row is inserted and never changed"),
        ]
        for build, message in refusals:
            with self.subTest(message=message), self.assertRaises(p.ConstructionError) as raised:
                build()
            self.assertIn(message, str(raised.exception))
        batch = Note.insert_many_for(ADMIN, [{"body": "x", "author_id": 10}]).add_for(ADA, {"body": "y"})
        self.assertEqual(len(batch.inspect().params), 6)

    # [spec:pgorm:req:bindings.scopes/test]    an update and a delete are held to the scopes, and a scope column is never updated
    def test_updates_and_deletes_hold_the_scopes(self):
        self.assertEqual(
            Note.update_for(ADA, {"body": "x"}).inspect().sql,
            'UPDATE "python_scopes"."note" SET "body" = $1 WHERE "note"."company_id" = $2 AND "note"."author_id" = $3',
        )
        self.assertEqual(
            Note.delete_for(ADMIN).where(Note.col("id") == 2).inspect().sql,
            'DELETE FROM "python_scopes"."note" WHERE "note"."company_id" = $1 AND "note"."id" = $2',
        )
        with self.assertRaises(p.ConstructionError) as raised:
            Note.update_for(ADMIN, {"author_id": 10})
        self.assertEqual(
            str(raised.exception),
            "`note`.`author_id` is written when its row is inserted and never changed",
        )

    # [spec:pgorm:req:bindings.scopes/test]    a pipeline from_for filters by each scope value, binding it
    def test_pipelines_filter_by_their_context(self):
        compiled = pl.from_for(ADA, Note).inspect()
        self.assertEqual(
            compiled.sql,
            'SELECT * FROM python_scopes.note WHERE company_id = $1 AND author_id = $2',
        )
        self.assertEqual(pl.from_for(ADMIN, Note).inspect().sql, "SELECT * FROM python_scopes.note WHERE company_id = $1")
        self.assertEqual(pl.from_for(ADA, Tag).inspect().sql, pl.from_(Tag).inspect().sql)


class Live(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.pool = p.Pool(os.environ["PGORM_TEST_DSN"], max_size=2)
        for statement in DDL:
            await self.pool.execute(p.RawSQL(statement))
        for identity, name in ((1, "Acme"), (2, "Globex")):
            await Company.insert_for(CompanyId(identity), {"name": name}).execute(self.pool)
        for company, author, body in ((1, 10, "Ada's plan"), (1, 11, "Bo's draft"), (2, 20, "Cy's memo")):
            await Note.insert_for(Member(CompanyId(company), UserId(author)), {"body": body}).execute(self.pool)
        await Tag.insert_many(
            [{"id": 1, "note_id": 1, "label": "plan"}, {"id": 2, "note_id": 2, "label": "draft"}]
        ).execute(self.pool)

    async def asyncTearDown(self):
        await self.pool.execute(p.RawSQL(f"DROP SCHEMA {SCHEMA} CASCADE"))
        await self.pool.close()

    def bodies(self, records):
        return sorted(record["body"] for record in records)

    # [spec:pgorm:req:bindings.scopes/test]    reads, graphs, joins, finds and pipelines return only the rows the context holds
    async def test_reads_return_the_contexts_rows(self):
        self.assertEqual(self.bodies(await Note.find_for(ADA).all(self.pool)), ["Ada's plan"])
        self.assertEqual(self.bodies(await Note.find_for(ADMIN).all(self.pool)), ["Ada's plan", "Bo's draft"])
        with self.assertRaises(p.DecodeError):
            await Note.find_by_key_for(ADA, {"id": 3}).one(self.pool)
        self.assertEqual(await Note.find_for(ADMIN).count(self.pool), 2)
        rows = await Company.graph_for(ADA).join_maybe(company_notes).all(self.pool)
        self.assertEqual([(company["name"], note and note["body"]) for company, note in rows], [("Acme", "Ada's plan")])
        joined = await Company.find_for(ADMIN).join_for(ADMIN, company_notes).all(self.pool)
        self.assertEqual([company["name"] for company in joined], ["Acme", "Acme"])
        tags = await Tag.find_for(ADA).all(self.pool)
        loaded = await tag_note.load(self.pool, tags, Note.find_for(ADA))
        self.assertEqual([None if note is None else note["body"] for note in loaded], ["Ada's plan", None])
        found = await note_tags.find_for(ADA, {"id": 1}).all(self.pool)
        self.assertEqual([tag["label"] for tag in found], ["plan"])
        piped = await pl.from_for(ADMIN, Note).into_model(Note).all(self.pool)
        self.assertEqual(self.bodies(piped), ["Ada's plan", "Bo's draft"])

    # [spec:pgorm:req:bindings.scopes/test]    writes fill the row, and an update or delete outside the scopes touches no row
    async def test_writes_reach_only_the_contexts_rows(self):
        written = await Note.insert_for(ADA, {"body": "Ada's second"}).returning().one(self.pool)
        self.assertEqual((written["company_id"], written["author_id"]), (1, 10))
        self.assertEqual(await Note.update_for(ADA, {"body": "x"}).where(Note.col("id") == 2).execute(self.pool), 0)
        self.assertEqual(await Note.update_for(ADMIN, {"body": "reviewed"}).where(Note.col("id") == 2).execute(self.pool), 1)
        self.assertEqual(await Note.delete_for(ADA).where(Note.col("id") == 2).execute(self.pool), 0)
        active = Note.active({"id": 2, "body": "again"})
        with self.assertRaises(p.DecodeError):
            await active.update_for(ADA, self.pool)
        self.assertEqual((await active.update_for(ADMIN, self.pool))["body"], "again")
        created = await Note.active({"body": "hooked"}).insert_for(ADA, self.pool)
        self.assertEqual(created["author_id"], 10)
        self.assertEqual(await Note.active({"id": created["id"]}).delete_for(CompanyAdmin(CompanyId(2), p.Every(UserId)), self.pool), 0)
        self.assertEqual(await Note.active({"id": created["id"]}).delete_for(ADA, self.pool), 1)
        with self.assertRaises(p.ConstructionError):
            await Note.active({"body": "x"}).insert(self.pool)
        self.assertEqual(self.bodies(await Note.find_for(ADMIN).all(self.pool)), ["Ada's plan", "Ada's second", "again"])


if __name__ == "__main__":
    unittest.main()

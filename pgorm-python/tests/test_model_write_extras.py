"""A declared model's writes beside the plain ones, against a live server:
try-inserts that say whether they wrote (pgorm's TryInsert), and updates and
deletes that read another table (UPDATE .. FROM, DELETE .. USING)."""

import os
import unittest

import pgorm as p

SCHEMA = "python_write_extras"

Shop = p.Model(
    "shop",
    {
        "id": p.Column("i32", primary_key=True, generated="by_default"),
        "name": p.Column("text"),
        "city": p.Column("text"),
    },
    schema=SCHEMA,
)
Item = p.Model(
    "item",
    {
        "id": p.Column("i32", primary_key=True),
        "shop_id": p.Column("i32"),
        "price": p.Column("i32"),
    },
    schema=SCHEMA,
)
Stock = p.Model(
    "stock",
    {"shop_id": p.Column("i32", primary_key=True), "item_id": p.Column("i32", primary_key=True)},
    schema=SCHEMA,
)
Note = p.Model("note", {"body": p.Column("text")}, schema=SCHEMA)
Tally = p.Model("tally", {"id": p.Column("i32", primary_key=True, generated="by_default")}, schema=SCHEMA)

DDL = [
    f"CREATE SCHEMA {SCHEMA}",
    f"""CREATE TABLE {SCHEMA}.shop (
        id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, city text NOT NULL
    )""",
    f"CREATE TABLE {SCHEMA}.item (id int4 PRIMARY KEY, shop_id int4 NOT NULL, price int4 NOT NULL)",
    f"CREATE TABLE {SCHEMA}.stock (shop_id int4, item_id int4, PRIMARY KEY (shop_id, item_id))",
    f"CREATE TABLE {SCHEMA}.note (body text NOT NULL UNIQUE)",
    f"CREATE TABLE {SCHEMA}.tally (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
]

Inserted, Conflicted, Empty = p.TryInsertResult.Inserted, p.TryInsertResult.Conflicted, p.TryInsertResult.Empty


class Construction(unittest.TestCase):
    # [spec:pgorm:req:bindings.model-try-inserts/test]    the conflict clause on the key, or on any key without one
    def test_try_insert_targets_the_primary_key(self):
        self.assertEqual(
            Stock.insert({"shop_id": 1, "item_id": 2}).on_conflict_do_nothing().inspect().sql,
            f'INSERT INTO "{SCHEMA}"."stock" ("shop_id", "item_id") VALUES ($1, $2) '
            'ON CONFLICT ("shop_id", "item_id") DO NOTHING',
        )
        self.assertTrue(
            Note.insert({"body": "x"}).on_conflict_do_nothing().inspect().sql.endswith(
                "ON CONFLICT DO NOTHING"
            )
        )
        plain = Stock.insert({"shop_id": 1, "item_id": 2}).on_empty_do_nothing()
        self.assertNotIn("ON CONFLICT", plain.inspect().sql)
        batch = Stock.insert({"shop_id": 1, "item_id": 2}).on_conflict_do_nothing().add(
            {"shop_id": 1, "item_id": 3}
        )
        self.assertIsInstance(batch, p.ModelTryInsertMany)
        self.assertIn("VALUES ($1, $2), ($3, $4) ON CONFLICT", batch.inspect().sql)
        self.assertIsInstance(Stock.insert_many([]).on_conflict_do_nothing(), p.ModelTryInsertMany)
        with self.assertRaises(p.ConstructionError):
            Stock.insert_many([]).on_conflict_do_nothing().inspect()
        with self.assertRaises(p.ConstructionError):
            bool(plain)

    # [spec:pgorm:req:bindings.model-write-sources/test]    FROM and USING name another model's table or a FROM item
    def test_update_from_and_delete_using(self):
        raised = (
            Item.update({"price": Item.col("price") + 1})
            .from_(Shop)
            .where(Item.col("shop_id") == Shop.col("id"))
            .where(Shop.col("city") == "Oslo")
        )
        self.assertEqual(
            raised.inspect().sql,
            f'UPDATE "{SCHEMA}"."item" SET "price" = "item"."price" + $1 FROM "{SCHEMA}"."shop" '
            'WHERE "item"."shop_id" = "shop"."id" AND "shop"."city" = $2',
        )
        gone = Item.delete().using(Shop.as_("s")).where(Item.col("shop_id") == Shop.as_("s").col("id"))
        self.assertEqual(
            gone.inspect().sql,
            f'DELETE FROM "{SCHEMA}"."item" USING "{SCHEMA}"."shop" AS "s" WHERE "item"."shop_id" = "s"."id"',
        )
        self.assertIn('USING "elsewhere"', Item.delete().using(p.Table("elsewhere")).all_rows().inspect().sql)
        with self.assertRaises(TypeError):
            Item.update({"price": 1}).from_("shop")  # type: ignore[arg-type]
        with self.assertRaises(TypeError):
            Item.delete().using(Shop.col("id"))  # type: ignore[arg-type]


class Writes(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.pool = p.Pool(os.environ["PGORM_TEST_DSN"], max_size=2)
        for statement in DDL:
            await self.pool.execute(p.RawSQL(statement))
        await Shop.insert_many(
            [{"name": "North", "city": "Oslo"}, {"name": "West", "city": "Bergen"}]
        ).execute(self.pool)
        await Item.insert_many(
            [
                {"id": 1, "shop_id": 1, "price": 10},
                {"id": 2, "shop_id": 1, "price": 20},
                {"id": 3, "shop_id": 2, "price": 30},
            ]
        ).execute(self.pool)
        await Stock.insert({"shop_id": 1, "item_id": 1}).execute(self.pool)

    async def asyncTearDown(self):
        await self.pool.execute(p.RawSQL(f"DROP SCHEMA {SCHEMA} CASCADE"))
        await self.pool.close()

    # [spec:pgorm:req:bindings.model-try-inserts/test]    inserted, conflicted or empty, as TryInsertResult answers
    async def test_try_insert_says_what_it_wrote(self):
        again = Stock.insert({"shop_id": 1, "item_id": 1}).on_conflict_do_nothing()
        self.assertEqual(await again.execute(self.pool), Conflicted())
        fresh = Stock.insert({"shop_id": 1, "item_id": 2}).on_conflict_do_nothing()
        self.assertEqual(await fresh.execute(self.pool), Inserted(1))
        mixed = Stock.insert_many(
            [{"shop_id": 1, "item_id": 2}, {"shop_id": 2, "item_id": 3}]
        ).on_conflict_do_nothing()
        self.assertEqual(await mixed.execute(self.pool), Inserted(1))
        self.assertEqual(await mixed.execute(self.pool), Conflicted())
        self.assertEqual(await Stock.insert_many([]).on_conflict_do_nothing().execute(self.pool), Empty())
        self.assertEqual(await Stock.insert_many([]).on_empty_do_nothing().execute(self.pool), Empty())
        # A row that sets no field is empty, and no row of defaults is written.
        defaults = Tally.insert({}).on_empty_do_nothing()
        self.assertEqual(await defaults.execute(self.pool), Empty())
        self.assertEqual(await Tally.find().count(self.pool), 0)
        match await Stock.insert({"shop_id": 2, "item_id": 1}).on_empty_do_nothing().execute(self.pool):
            case Inserted(count):
                self.assertEqual(count, 1)
            case other:
                self.fail(f"the row is new: {other!r}")
        # An insert of no rows takes a conflict clause and still sends nothing.
        self.assertEqual(
            await Stock.insert_many([]).on_conflict(p.Conflict.do_nothing()).execute(self.pool), 0
        )

    # [spec:pgorm:req:bindings.model-try-inserts/test]    RETURNING answers with the rows written
    async def test_try_insert_returns_what_it_wrote(self):
        row = Shop.insert({"id": 1, "name": "North", "city": "Oslo"}).on_conflict_do_nothing()
        self.assertEqual(await row.returning("name").one(self.pool), Conflicted())
        match await Shop.insert({"name": "East", "city": "Tromsø"}).on_conflict_do_nothing().returning().one(
            self.pool
        ):
            case Inserted(record):
                self.assertEqual((record["id"], record["name"]), (3, "East"))
            case other:
                self.fail(f"East is new: {other!r}")
        batch = Stock.insert_many(
            [{"shop_id": 1, "item_id": 1}, {"shop_id": 1, "item_id": 3}]
        ).on_conflict_do_nothing()
        written = await batch.returning().all(self.pool)
        self.assertIsInstance(written, Inserted)
        assert isinstance(written, Inserted)
        self.assertEqual([dict(record) for record in written.value], [{"shop_id": 1, "item_id": 3}])
        self.assertEqual(await batch.returning().all(self.pool), Conflicted())
        self.assertEqual(await Stock.insert_many([]).on_empty_do_nothing().returning().all(self.pool), Empty())
        self.assertEqual(await Tally.insert({}).on_empty_do_nothing().returning().one(self.pool), Empty())

    # [spec:pgorm:req:bindings.model-write-sources/test]    the rows another table picks are written
    async def test_writes_read_another_table(self):
        raised = (
            Item.update({"price": Item.col("price") + 1})
            .from_(Shop)
            .where(Item.col("shop_id") == Shop.col("id"))
            .where(Shop.col("city") == "Oslo")
        )
        self.assertEqual(await raised.execute(self.pool), 2)
        prices = await Item.select("price").order_by(Item.col("id").asc()).all(self.pool)
        self.assertEqual([row["price"] for row in prices], [11, 21, 30])
        gone = (
            Item.delete()
            .using(Shop)
            .where(Item.col("shop_id") == Shop.col("id"))
            .where(Shop.col("city") == "Bergen")
        )
        self.assertTrue(gone.returning("id").inspect().sql.endswith('RETURNING "item"."id"'))
        removed = await gone.returning("id").all(self.pool)
        self.assertEqual([row["id"] for row in removed], [3])


if __name__ == "__main__":
    unittest.main()

"""A binary COPY's rows one at a time: described columns, the row sink, a
model's records both ways, and the format framed by the program itself."""

import asyncio
from decimal import Decimal
import os
import unittest

import pgorm as p


def cakes() -> p.Model:
    return p.Model(
        "python_copy_cakes",
        {
            "id": p.Column("i32", primary_key=True, generated="by_default"),
            "name": p.Column("text"),
            "mood": p.Column(p.TypeName("python_copy_cake_mood", schema="public"), values=["sweet", "sour"]),
            "price": p.Column("decimal", name="unit price"),
        },
    )


class CopyRowSurface(unittest.IsolatedAsyncioTestCase):
    async def drop(self) -> None:
        for statement in (
            "DROP TABLE IF EXISTS python_copy_cakes",
            "DROP TYPE IF EXISTS python_copy_cake_mood",
        ):
            await self.pool.execute(p.RawSQL(statement))

    async def asyncSetUp(self) -> None:
        self.pool = p.Pool(os.environ["PGORM_TEST_DSN"], max_size=3)
        await self.drop()
        await self.pool.execute(p.RawSQL("CREATE TYPE python_copy_cake_mood AS ENUM ('sweet', 'sour')"))
        await self.pool.execute(p.RawSQL(
            "CREATE TABLE python_copy_cakes (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            'name text NOT NULL, mood python_copy_cake_mood NOT NULL, "unit price" numeric(6, 2) NOT NULL)'
        ))
        self.table = p.Table("python_copy_cakes")
        self.into = p.CopyFrom(self.table, "binary").columns("name", "mood", "unit price")

    async def asyncTearDown(self) -> None:
        await self.drop()
        await asyncio.wait_for(self.pool.close(), 2)

    async def count(self) -> int:
        value: int = (await self.pool.one(p.RawSQL("SELECT count(*)::int AS n FROM python_copy_cakes")))["n"]
        return value

    # [spec:pgorm:req:bindings.copy-rows+2/test]    described columns carry their types,
    # an enum's schema-qualified, for a COPY in any format, without starting it
    async def test_columns_are_described_with_their_types(self) -> None:
        columns = await self.pool.copy_in_columns(self.into)
        self.assertEqual([column.name for column in columns], ["name", "mood", "unit price"])
        self.assertEqual(
            [(column.type.schema, column.type.name) for column in columns],
            [("pg_catalog", "text"), ("public", "python_copy_cake_mood"), ("pg_catalog", "numeric")],
        )
        async with self.pool.connection() as connection:
            out = await connection.copy_out_columns(p.CopyTo(self.table, "csv"))
            self.assertEqual([column.name for column in out], ["id", "name", "mood", "unit price"])
            with self.assertRaises(p.DatabaseError) as caught:
                await connection.copy_in_columns(p.CopyFrom(p.Table("python_copy_missing"), "text"))
            self.assertEqual(caught.exception.sqlstate, "42P01")
            self.assertTrue(await connection.ping())
        async with self.pool.transaction() as tx:
            self.assertEqual(len(await tx.copy_in_columns(self.into)), 3)
        self.assertEqual(await self.count(), 0)

    # [spec:pgorm:req:bindings.copy-rows+2/test]    a sink takes rows one at a time, a
    # refused row leaving it taking rows, and finish counts the rows written
    async def test_a_sink_takes_one_row_at_once(self) -> None:
        async with await self.pool.copy_in_rows(self.into) as sink:
            self.assertEqual([column.name for column in sink.columns], ["name", "mood", "unit price"])
            await sink.send(["Lemon", "sour", Decimal("3.50")])
            with self.assertRaises(p.ConstructionError):
                await sink.send(["Short"])
            await sink.send(("Honey", "sweet", Decimal("4.25")))
            self.assertEqual(await sink.finish(), 2)
        self.assertEqual(await self.count(), 2)

    # [spec:pgorm:req:bindings.copy-rows+2/test]    a sink left unfinished writes nothing
    async def test_an_unfinished_sink_writes_nothing(self) -> None:
        async with self.pool.connection() as connection:
            async with await connection.copy_in_rows(self.into) as sink:
                await sink.send(["Plum", "sweet", Decimal("2.00")])
            self.assertTrue(sink.closed)
            self.assertTrue(await connection.ping())
        self.assertEqual(await self.count(), 0)

    # [spec:pgorm:req:bindings.copy-rows+2/test]    rows read as a model's records and
    # written back as them
    async def test_model_records_round_trip(self) -> None:
        model = cakes()
        await self.pool.execute(p.RawSQL(
            "INSERT INTO python_copy_cakes (name, mood, \"unit price\") VALUES ('Lemon', 'sour', 3.50), ('Honey', 'sweet', 4.25)"
        ))
        source = p.CopyTo(p.select(self.table.star()).from_(self.table).order_by(self.table.col("id").asc()), "binary")
        records = [record async for record in (await self.pool.copy_out_rows(source)).models(model)]
        self.assertEqual([(record["name"], record["price"]) for record in records],
                         [("Lemon", Decimal("3.50")), ("Honey", Decimal("4.25"))])
        async with self.pool.transaction() as tx:
            sink = await tx.copy_in_rows(self.into)
            for record in records:
                await sink.send_model(record)
            self.assertEqual(await sink.finish(), 2)
        self.assertEqual(await self.count(), 4)
        # A record of a model reading fewer columns has no field for the others.
        names = p.Model("python_copy_cakes", {"id": p.Column("i32", primary_key=True), "name": p.Column("text")})
        narrow = p.CopyTo(p.select(self.table.col("id"), self.table.col("name")).from_(self.table), "binary")
        named = [record async for record in (await self.pool.copy_out_rows(narrow)).models(names)]
        async with await self.pool.copy_in_rows(self.into) as sink:
            with self.assertRaises(p.ConstructionError):
                await sink.send_model(named[0])
        self.assertEqual(await self.count(), 4)

    # [spec:pgorm:req:bindings.copy-rows+2/test]    the program frames the binary format
    # itself, and the decoder takes the data split anywhere
    async def test_encoder_and_decoder_frame_the_format(self) -> None:
        columns = [p.CopyColumn("name", "text"), p.CopyColumn("mood", "text"), p.CopyColumn("unit price", "numeric")]
        encoder = p.CopyRowEncoder(columns)
        data = (
            p.CopyRowEncoder.header()
            + encoder.encode(["Noon", "sweet", Decimal("1.10")])
            + encoder.encode(["Dusk", "sour", Decimal("2.20")])
            + p.CopyRowEncoder.trailer()
        )
        self.assertEqual(await self.pool.copy_in(p.CopyFrom(self.table, "binary").columns("name", "mood", "unit price"), data), 2)
        with self.assertRaises(p.ConstructionError):
            encoder.encode(["Short"])
        decoder = p.CopyRowDecoder(columns)
        rows = []
        for index in range(len(data)):
            decoder.push(data[index:index + 1])
            while (row := decoder.next_row()) is not None:
                rows.append(row)
        decoder.finish()
        self.assertEqual(rows, [("Noon", "sweet", Decimal("1.10")), ("Dusk", "sour", Decimal("2.20"))])
        truncated = p.CopyRowDecoder(columns)
        truncated.push(data[:-5])
        while truncated.next_row() is not None:
            pass
        with self.assertRaises(p.DecodeError):
            truncated.finish()

    # [spec:pgorm:req:bindings.copy-rows+2/test]    a column of a built-in type is built
    # by its name; another type, or money without its places, is refused
    def test_columns_a_program_builds(self) -> None:
        column = p.CopyColumn("tags", "text[]")
        self.assertEqual((column.name, column.type.name, column.type.schema), ("tags", "_text", "pg_catalog"))
        self.assertEqual(p.CopyColumn("cash", "money", money_places=2).money_places, 2)
        for name, kind, places in (("mood", "python_copy_cake_mood", None), ("cash", "money", None), ("name", "text", 2)):
            with self.subTest(kind=kind):
                with self.assertRaises(p.ConstructionError):
                    p.CopyColumn(name, kind, money_places=places)
        with self.assertRaises(TypeError):
            p.CopyColumn("name", 7)  # type: ignore[arg-type]


if __name__ == "__main__":
    unittest.main()

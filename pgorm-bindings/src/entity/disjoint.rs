//! Disjoint models and registered `#[derive(Disjoint)]` enums, over pgorm's
//! [`DisjointShape`].
//!
//! Either is one [`DisjointCore`]: a shape, from models a program declares
//! or from the registered enum, and a codec reading each row back. Every
//! statement is the shape's, so a model's statements are the ones the Rust
//! declaration of the same tables sends; the codec only reads the rows back,
//! a model's as values the binding views by field and a registration's as
//! its entities' own models.

use std::{any::TypeId, fmt, sync::Arc};

use pgorm::pgorm_query::{ColumnType, Name, SqlName, TableName};
use pgorm::{
    ActiveValue, ColumnTypeTrait, Disjoint, DisjointColumn, DisjointShape, DisjointTable,
    DisjointValues, Iterable, KindModel, KindVisitor, QueryResult,
};
use serde_json::Value as Json;

use super::{Active, EntityBackend, EntityInfo, Model, Registry, object, registration_name};
use crate::{Dialect, Failure, Tag, TypeName};

/// A registered entity, as a disjoint registration's base or kind.
pub type Entity = Arc<dyn EntityBackend>;

/// How a disjoint read's rows become records: as values a model views by
/// field, or as the registered entities' own models.
#[derive(Debug)]
pub enum RowCodec {
    /// A model the program declares, whose rows the binding reads as values.
    Models,
    /// A registered enum, whose rows decode as its entities' models.
    Entities {
        /// The entity of the base table every kind shares.
        base: Entity,
        /// Each kind's entity, `None` for a kind without a table.
        kinds: Vec<Option<Entity>>,
    },
}

/// One disjoint model or registration: its shape, its codec, and its
/// description.
#[allow(missing_docs)]
pub struct DisjointCore {
    pub shape: DisjointShape,
    pub codec: RowCodec,
    /// What `describe()` reports, spelled by the binding's rule.
    pub description: Json,
    /// The registered enum's type, which no second registration may name.
    rust: Option<TypeId>,
}

impl fmt::Debug for DisjointCore {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("DisjointCore")
            .field("description", &self.description)
            .finish_non_exhaustive()
    }
}

/// How a described model column is generated.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Generated {
    /// `GENERATED ALWAYS AS IDENTITY`.
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault,
}

/// One model column, as a binding reads its description.
#[derive(Clone, Debug)]
#[allow(missing_docs)]
pub struct DescribedColumn {
    pub name: String,
    /// The kind its values are, an array's included.
    pub kind: Tag,
    /// An enum column's labels.
    pub values: Vec<String>,
    pub nullable: bool,
    /// Whether, and how, it is an identity column.
    pub generated: Option<Generated>,
    /// Whether the table fills it when a write states nothing for it.
    pub default: bool,
}

impl DescribedColumn {
    /// The column, its type, nullability and identity as pgorm's
    /// `DisjointColumn` holds them, refused for a kind no column decodes as.
    pub fn column(self) -> Result<DisjointColumn, Failure> {
        let mut def = self.kind.column_type(&self.values)?.def();
        if self.nullable {
            def = def.nullable();
        }
        def = match self.generated {
            Some(Generated::Always) => def.identity(),
            Some(Generated::ByDefault) => def.identity_by_default(),
            None => def,
        };
        let column = DisjointColumn::new(self.name, def);
        Ok(match self.default {
            true => column.with_unstated_default(),
            false => column,
        })
    }
}

/// A unique key of a model's table, as a binding reads its description.
#[derive(Clone, Debug)]
pub struct DescribedKey {
    /// The constraint's name, `None` for PostgreSQL to choose one.
    pub name: Option<String>,
    /// Its columns, in key order.
    pub columns: Vec<String>,
    /// Whether nulls are equal under it.
    pub nulls_not_distinct: bool,
}

/// One model's table, as a binding reads its description: its schema, its
/// name, its columns in field order, its key's columns and its unique keys.
#[derive(Debug)]
#[allow(missing_docs)]
pub struct DescribedTable {
    /// Its schema, `None` for the search path's.
    pub schema: Option<String>,
    pub table: String,
    pub columns: Vec<DisjointColumn>,
    /// Its primary key's columns, in key order.
    pub key: Vec<String>,
    pub unique_keys: Vec<DescribedKey>,
}

impl DescribedTable {
    /// The table the description is, refused as pgorm's `DisjointTable`
    /// refuses it.
    // [spec:pgorm:req:bindings.model-unique-keys+2]
    pub fn table(self) -> Result<DisjointTable, Failure> {
        let construction = |error: pgorm::Error| Failure::Construction(error.to_string());
        let name = match self.schema {
            Some(schema) => {
                TableName::SchemaTable(Name::runtime(schema), Name::runtime(self.table))
            }
            None => TableName::Table(Name::runtime(self.table)),
        };
        let key: Vec<&str> = self.key.iter().map(String::as_str).collect();
        let mut table = DisjointTable::new(name, self.columns, &key).map_err(construction)?;
        for unique in &self.unique_keys {
            let columns: Vec<&str> = unique.columns.iter().map(String::as_str).collect();
            table = table
                .with_unique_key(unique.name.as_deref(), &columns, unique.nulls_not_distinct)
                .map_err(construction)?;
        }
        Ok(table)
    }
}

/// Where a kinded model's base holds each row's kind: the column, the field
/// it is the column of, and the kind type.
#[derive(Clone, Debug)]
#[allow(missing_docs)]
pub struct Kinded {
    pub column: String,
    pub field: String,
    /// The enum type the kinds are labels of.
    pub kind_type: TypeName,
}

/// What a write of a kind gives the kind's own row.
#[derive(Debug)]
pub enum KindRow<'a> {
    /// A kind without a table, given no row's values.
    Absent,
    /// A kind with a table, given none: the row of its defaults.
    Empty(DisjointValues),
    /// A kind with a table, given its row's values, which the binding reads
    /// into the table, through the kind's entity for a registration.
    Given {
        /// The kind's table.
        table: &'a DisjointTable,
        /// The kind's entity, for a registration.
        entity: Option<&'a Entity>,
    },
}

/// A registration's decoded row: its base model, its kind, and its kind's
/// model, `None` for a kind without a table.
#[derive(Debug)]
#[allow(missing_docs)]
pub struct EntityRow {
    pub base: Model,
    pub kind: String,
    pub row: Option<Model>,
}

/// A judged row of a model: the index of its kind and the decoded source
/// its kind's row is under.
#[derive(Clone, Copy, Debug)]
#[allow(missing_docs)]
pub struct Judged {
    pub kind: usize,
    /// The decoded source of the kind's row, `None` for a kind without one.
    pub source: Option<usize>,
}

impl DisjointCore {
    /// The disjoint model `name` over the described `base` and each kind in
    /// order, its value beside its model's name and table, or `None` for a
    /// kind without one. A kinded model is kinded by `kinded`; an unkinded
    /// model's base holds no kind. What the shape refuses is refused.
    // [spec:pgorm:req:bindings.disjoint+2]
    // [spec:pgorm:req:bindings.disjoint-unkinded]
    pub fn model(
        dialect: Dialect,
        name: &str,
        base: (String, DisjointTable),
        kinded: Option<Kinded>,
        kinds: Vec<(String, Option<(String, DisjointTable)>)>,
    ) -> Result<Self, Failure> {
        let (base_name, base) = base;
        let mut described = Vec::with_capacity(kinds.len());
        let mut tables = Vec::with_capacity(kinds.len());
        for (value, table) in kinds {
            let (model, table) = match table {
                Some((model, table)) => (Json::from(model), Some(table)),
                None => (Json::Null, None),
            };
            described.push(object(
                dialect,
                [("value", value.clone().into()), ("model", model)],
            ));
            tables.push((value, table));
        }
        let (shape, kind_field, kind_type) = match kinded {
            Some(kinded) => (
                DisjointShape::new(base, &kinded.column, kinded.kind_type.rust_type(), tables),
                Json::from(kinded.field),
                object(
                    dialect,
                    [
                        ("schema", kinded.kind_type.schema.into()),
                        ("name", kinded.kind_type.name.into()),
                    ],
                ),
            ),
            None => (
                DisjointShape::unkinded(base, tables),
                Json::Null,
                object(dialect, [("schema", Json::Null), ("name", Json::Null)]),
            ),
        };
        Ok(Self {
            shape: shape.map_err(|error| Failure::Construction(error.to_string()))?,
            codec: RowCodec::Models,
            description: object(
                dialect,
                [
                    ("name", name.into()),
                    ("base", base_name.into()),
                    ("kind_field", kind_field),
                    ("kind_type", kind_type),
                    ("kinds", described.into()),
                ],
            ),
            rust: None,
        })
    }

    /// The kind `kind`'s index.
    pub fn kind_index(&self, kind: &str) -> Result<usize, Failure> {
        self.shape
            .kind(kind)
            .map(|(index, _)| index)
            .map_err(|error| Failure::Construction(error.to_string()))
    }

    /// The kinds' values, in order.
    pub fn kinds(&self) -> Vec<String> {
        self.shape
            .kinds()
            .iter()
            .map(|kind| kind.value().to_owned())
            .collect()
    }

    /// The SQL names of the base's key columns, in key order.
    pub fn key_names(&self) -> Vec<String> {
        self.shape
            .base()
            .key()
            .map(|column| column.name().to_string())
            .collect()
    }

    /// The entity of the base, and of the kind at `index`, of a
    /// registration.
    pub fn entities(&self, index: usize) -> (Option<&Entity>, Option<&Entity>) {
        match &self.codec {
            RowCodec::Models => (None, None),
            RowCodec::Entities { base, kinds } => (Some(base), kinds[index].as_ref()),
        }
    }

    /// What a write of the kind `kind` gives its own row, `given` saying
    /// whether the write gives that row's values: a kind without a table
    /// given them is refused.
    // [spec:pgorm:req:bindings.disjoint+2]
    pub fn kind_row(&self, kind: &str, given: bool) -> Result<KindRow<'_>, Failure> {
        let (position, entry) = self
            .shape
            .kind(kind)
            .map_err(|error| Failure::Construction(error.to_string()))?;
        match (entry.table(), given) {
            (Some(table), true) => Ok(KindRow::Given {
                table,
                entity: self.entities(position).1,
            }),
            (Some(table), false) => table
                .values(Vec::<(String, _)>::new())
                .map(KindRow::Empty)
                .map_err(|error| Failure::Construction(error.to_string())),
            (None, true) => Err(Failure::Construction(format!(
                "the kind `{kind}` has no table, so a write of it gives no row's values"
            ))),
            (None, false) => Ok(KindRow::Absent),
        }
    }

    /// Where each enum column of every source is in a read's result, by its
    /// result name, and its kind: the read projects one as its text, as
    /// pgorm's `ColumnTrait::select_as` reads an entity's, and a model's
    /// field is the enum its column names.
    pub fn enum_columns(&self) -> Vec<(String, Tag)> {
        let shape = &self.shape;
        let tables = std::iter::once((0, shape.base()))
            .chain(shape.sources().map(|(source, _, table)| (source, table)));
        let mut found = Vec::new();
        for (source, table) in tables {
            let names = shape.result_names(source).unwrap_or_default();
            for (column, result_name) in table.columns().iter().zip(names) {
                let (column_type, array) = match column.def().get_column_type() {
                    ColumnType::Array(element) => (element.as_ref(), true),
                    column_type => (column_type, false),
                };
                let (ColumnType::Enum { .. }, Some(tag)) =
                    (column_type, Tag::of_column(column_type))
                else {
                    continue;
                };
                found.push((
                    result_name,
                    match array {
                        true => Tag::Array(Box::new(tag)),
                        false => tag,
                    },
                ));
            }
        }
        found
    }

    /// Judge a model's row by its kind, `value` giving the text of the
    /// result column of a name, which an error naming the row's key reads.
    // [spec:pgorm:req:bindings.disjoint+2]
    pub fn judge(
        &self,
        row: &QueryResult,
        value: impl Fn(&str) -> Option<String>,
    ) -> Result<Judged, Failure> {
        let key = || {
            let prefix = pgorm::source_prefix(0);
            self.shape
                .base()
                .key()
                .map(|column| {
                    value(&pgorm::result_column_name(
                        &prefix,
                        &column.name().to_string(),
                    ))
                    .unwrap_or_default()
                })
                .collect()
        };
        let judged = self
            .shape
            .judge(row, key)
            .map_err(|error| Failure::Decode(error.to_string()))?;
        Ok(Judged {
            kind: judged.kind,
            source: judged.source,
        })
    }

    /// A registration's row, judged by its kind and decoded by its entities.
    // [spec:pgorm:req:bindings.disjoint+2]
    pub fn entity_row(&self, row: &QueryResult) -> Result<EntityRow, Failure> {
        let RowCodec::Entities { base, kinds } = &self.codec else {
            return Err(Failure::Internal(
                "a disjoint model's rows have no entities".to_owned(),
            ));
        };
        let shape = &self.shape;
        let model = base
            .decode(row, &pgorm::source_prefix(0))
            .map_err(|error| Failure::Decode(error.to_string()))?;
        let key = || {
            shape
                .base()
                .key()
                .map(|column| {
                    model
                        .get(&column.name().to_string())
                        .map(|value| value.to_string())
                        .unwrap_or_default()
                })
                .collect()
        };
        let judged = shape
            .judge(row, key)
            .map_err(|error| Failure::Decode(error.to_string()))?;
        let kind_row = match (judged.source, &kinds[judged.kind]) {
            (Some(source), Some(entity)) => Some(
                entity
                    .decode(row, &pgorm::source_prefix(source))
                    .map_err(|error| Failure::Decode(error.to_string()))?,
            ),
            _ => None,
        };
        Ok(EntityRow {
            base: model,
            kind: shape.kinds()[judged.kind].value().to_owned(),
            row: kind_row,
        })
    }
}

/// The refusal, a binding's `TypeError`, of an ActiveModel `active` of
/// another registration than `entity`.
pub fn foreign_active(entity: &EntityInfo, active: &EntityInfo) -> Option<String> {
    (active.name != entity.name).then(|| {
        format!(
            "the ActiveModel is {}'s, not {}'s",
            active.name, entity.name
        )
    })
}

/// What `active`, an ActiveModel of `entity`, gives `table`'s columns.
// [spec:pgorm:req:bindings.disjoint+2]
pub fn active_values(
    table: &DisjointTable,
    entity: &Entity,
    active: &Active,
) -> Result<DisjointValues, Failure> {
    let values = entity
        .info()
        .columns
        .iter()
        .map(|column| Ok((column.name.clone(), active.get(&column.name)?)))
        .collect::<Result<Vec<(String, ActiveValue<_>)>, Failure>>()?;
    table
        .values(values)
        .map_err(|error| Failure::Construction(error.to_string()))
}

/// Finds each kind's registered entity.
struct Kinds<'r>(&'r Registry);

impl<D: Disjoint> KindVisitor<D> for Kinds<'_> {
    type Output = Result<Option<Entity>, Failure>;

    fn table<M: KindModel<D>>(self, _: D::Kind) -> Self::Output {
        self.0
            .backend::<M::Entity>("the disjoint entity over it")
            .map(Some)
    }

    fn unit(self, _: D) -> Self::Output {
        Ok(None)
    }
}

impl Registry {
    /// Register the `#[derive(Disjoint)]` enum `D` under `name`, its base and
    /// each kind's entity registered before it. A name or an enum registered
    /// twice, an entity not registered, and a declaration `check_disjoint`
    /// refuses are each refused, and nothing is added. An unkinded enum
    /// registers the same way and is read-only: its shape refuses every
    /// write and its schema.
    // [spec:pgorm:req:bindings.disjoint+2]
    // [spec:pgorm:req:bindings.disjoint-unkinded]
    // [spec:pgorm:req:bindings.entities+6]
    // [spec:pgorm:sem:disjoint.unkinded+1]
    pub fn disjoint<D: Disjoint + 'static>(&mut self, name: &str) -> Result<(), Failure> {
        registration_name(name)?;
        let rust = TypeId::of::<D>();
        if self.disjoints.contains_key(name)
            || self.disjoints.values().any(|core| core.rust == Some(rust))
        {
            return Err(Failure::Construction(format!(
                "{name:?} or its Rust disjoint enum is already registered"
            )));
        }
        let shape = DisjointShape::of::<D>();
        shape
            .check()
            .map_err(|error| Failure::Construction(error.to_string()))?;
        let base = self.backend::<D::Base>("the disjoint entity over it")?;
        let kinds = D::Kind::iter()
            .map(|kind| D::visit_kind(kind, Kinds(self)))
            .collect::<Result<Vec<_>, _>>()?;
        let dialect = self.dialect();
        let kind_type = shape.kind_type_name();
        let description = object(
            dialect,
            [
                ("name", name.into()),
                ("base", base.info().name.clone().into()),
                (
                    "kind_field",
                    shape
                        .kind_column()
                        .map(|column| column.name().to_string())
                        .into(),
                ),
                (
                    "kind_type",
                    object(
                        dialect,
                        [
                            (
                                "schema",
                                kind_type
                                    .as_ref()
                                    .and_then(|name| name.schema.as_ref())
                                    .map(|schema| SqlName::to_string(&**schema))
                                    .into(),
                            ),
                            (
                                "name",
                                kind_type.map(|name| SqlName::to_string(&*name.name)).into(),
                            ),
                        ],
                    ),
                ),
                (
                    "kinds",
                    shape
                        .kinds()
                        .iter()
                        .zip(&kinds)
                        .map(|(kind, entity)| {
                            object(
                                dialect,
                                [
                                    ("value", kind.value().into()),
                                    (
                                        "model",
                                        entity
                                            .as_ref()
                                            .map(|entity| entity.info().name.clone())
                                            .into(),
                                    ),
                                ],
                            )
                        })
                        .collect::<Vec<_>>()
                        .into(),
                ),
            ],
        );
        self.disjoints.insert(
            name.to_owned(),
            Arc::new(DisjointCore {
                shape,
                codec: RowCodec::Entities { base, kinds },
                description,
                rust: Some(rust),
            }),
        );
        Ok(())
    }
}

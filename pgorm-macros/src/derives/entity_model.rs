/// The most columns a primary key can have: `PrimaryKeyTrait::ValueType` is a
/// tuple for a composite key, and its traits are implemented for tuples of 1
/// through 12 parts.
// [spec:pgorm:sem:macros.derive.entity-model.primary-key+7]
const MAX_KEY_ARITY: usize = 12;

/// The field-level `#[pgorm(...)]` configuration of one model field.
#[derive(Default)]
struct FieldAttrs {
    sql_type: Option<Expr>,
    column_name: Option<String>,
    /// The `Column` variant the field names in place of the one its name
    /// derives.
    variant: Option<Ident>,
    comment: Option<Lit>,
    default_value: Option<Expr>,
    default_expr: Option<Expr>,
    /// How the column is read: a verbatim cast or a function of its
    /// expression, never both.
    select: Option<Conversion>,
    /// How a value is written to the column, and an array of its values.
    save: Option<Conversion>,
    /// Where `save_array_with` was written, and the function it names.
    save_array_with: Option<(Path, Span)>,
    /// Where this field's `primary_key` key was written, when it was.
    primary_key: Option<Span>,
    /// Where this field's `without_overlaps` key was written: the key's
    /// period, compared for overlap.
    without_overlaps: Option<Span>,
    nullable: bool,
    indexed: bool,
    unique: bool,
    ignore: bool,
    /// The `auto_increment = ..` this field wrote, and where.
    auto_increment: Option<(bool, Span)>,
    /// The identity this field declared, as the builder call it becomes, and
    /// where.
    identity: Option<(Identity, Span)>,
    /// The generated column this field declared: its kind, its expression,
    /// and where the key was written.
    generated: Option<(Generated, Expr, Span)>,
}

/// Which of PostgreSQL's two identity forms a field declared.
#[derive(Clone, Copy)]
enum Identity {
    /// `identity`: `GENERATED ALWAYS AS IDENTITY`.
    Always,
    /// `identity_by_default`: `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault,
}

impl Identity {
    /// The `ColumnDef` builder call that declares this form.
    fn builder(self) -> TokenStream {
        match self {
            Self::Always => quote! { .identity() },
            Self::ByDefault => quote! { .identity_by_default() },
        }
    }
}

/// Which of PostgreSQL's two kinds of generated column a field declared.
#[derive(Clone, Copy, PartialEq)]
enum Generated {
    /// `generated_stored`: `GENERATED ALWAYS AS (..) STORED`.
    Stored,
    /// `generated_virtual`: `GENERATED ALWAYS AS (..) VIRTUAL`.
    Virtual,
}

impl Generated {
    /// The `ColumnDef` builder call that declares this kind over `expr`.
    fn builder(self, expr: &Expr) -> TokenStream {
        let kind = match self {
            Self::Stored => quote! { Stored },
            Self::Virtual => quote! { Virtual },
        };
        quote! { .generated(#expr, pgorm::pgorm_query::GeneratedKind::#kind) }
    }
}

/// How a column's expression becomes the one read, or a value the one
/// written: a cast to a type the entity's author wrote out as SQL
/// (`select_as`, `save_as`), or a function of the expression
/// (`select_with`, `save_with`) for what a fixed cast cannot say.
enum Conversion {
    /// The type, verbatim: `BIT(8)`, `numeric(10,2)`.
    Cast(String),
    /// The function, `fn(Expr) -> SimpleExpr`, and where its key was written.
    With(Path, Span),
}

/// The two keys of one direction of [`Conversion`], and the word its refusal
/// uses.
struct Direction {
    cast: &'static str,
    with: &'static str,
    verb: &'static str,
}

const READ: Direction = Direction {
    cast: "select_as",
    with: "select_with",
    verb: "read",
};

const WRITE: Direction = Direction {
    cast: "save_as",
    with: "save_with",
    verb: "written",
};

/// The conversion `meta` declares. A column is converted one way in each
/// direction, so a second key of the pair, or the same key again, is refused
/// rather than left to override the first.
// [spec:pgorm:req:macros.derive.one-form]
// [spec:pgorm:syn:macros.derive.entity-model.attrs+7]
fn conversion(
    meta: &ParseNestedMeta,
    declared: &Option<Conversion>,
    direction: Direction,
) -> syn::Result<Conversion> {
    let Direction { cast, with, verb } = direction;
    if declared.is_some() {
        return Err(meta.error(format!(
            "a column is {verb} one way: `{cast}` or `{with}`, once"
        )));
    }
    if meta.path.is_ident(cast) {
        let lit = meta.value()?.parse()?;
        let Lit::Str(litstr) = lit else {
            return Err(meta.error(format!("Invalid {cast} {lit:?}")));
        };
        return Ok(Conversion::Cast(litstr.value()));
    }
    Ok(Conversion::With(bare_code(meta, with)?, meta.path.span()))
}

/// The expressions a column's `save_as` and `save_array_as` overrides write a
/// value and an array of values through.
struct Written {
    value: TokenStream,
    array: TokenStream,
}

/// The expression a column's `select_as` override reads it through, and what
/// its `save_as` / `save_array_as` overrides write through: `None` where the
/// field declared none, leaving the trait's casts. A `save_with` needs a
/// `save_array_with` beside it, since the array `= ANY` and `<> ALL` compare a
/// column with is not a value of the column's type.
// [spec:pgorm:req:macros.derive.one-form]
// [spec:pgorm:sem:macros.derive.entity-model+8]
fn conversion_arms(
    select: Option<Conversion>,
    save: Option<Conversion>,
    save_array_with: Option<(Path, Span)>,
) -> syn::Result<(Option<TokenStream>, Option<Written>)> {
    // `select_as` / `save_as` carry a type *expression* authored in the
    // entity's own source — `BIT(8)`, `numeric(10,2)` — which is not an
    // identifier and must not be quoted as one.
    let read = select.map(|select| match select {
        Conversion::Cast(select_as) => quote! { expr.cast_as_raw(#select_as) },
        Conversion::With(select_with, _) => quote! { #select_with(expr) },
    });
    let written = match (save, save_array_with) {
        (Some(Conversion::Cast(save_as)), None) => Some(Written {
            value: quote! { val.cast_as_raw(#save_as) },
            array: quote! { val.cast_as_raw(concat!(#save_as, "[]")) },
        }),
        (Some(Conversion::With(save_with, _)), Some((save_array_with, _))) => Some(Written {
            value: quote! { #save_with(val) },
            array: quote! { #save_array_with(val) },
        }),
        (Some(Conversion::With(_, span)), None) => {
            return Err(syn::Error::new(
                span,
                "a column written through `save_with` names `save_array_with` too: the \
                 function writing an array of its values, which `= ANY` and `<> ALL` \
                 compare it with",
            ));
        }
        (_, Some((_, span))) => {
            return Err(syn::Error::new(
                span,
                "`save_array_with` writes an array of the values `save_with` writes one \
                 of; name `save_with` beside it",
            ));
        }
        (None, None) => None,
    };
    Ok((read, written))
}

/// `column_name` carries the name derived before any attribute is read, which an
/// explicit `column_name` key overrides. `auto_increment` and `primary_key_types`
/// are entity-wide and accumulate across every field. A key whose value is Rust
/// code takes it bare; `default_value` is an expression of the column's value,
/// so a string literal there is that string.
// [spec:pgorm:syn:macros.derive.entity-model.attrs+7]
// [spec:pgorm:req:macros.derive.code-values+2]
fn parse_field_attrs(
    field: &Field,
    column_name: Option<String>,
    auto_increment: &mut bool,
    primary_key_types: &mut Punctuated<Type, Comma>,
) -> syn::Result<FieldAttrs> {
    let mut parsed = FieldAttrs {
        column_name,
        ..Default::default()
    };

    for attr in field.attrs.iter() {
        if !attr.path().is_ident("pgorm") {
            continue;
        }

        // single param
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("column_type") {
                parsed.sql_type = Some(bare_code(&meta, "column_type")?);
            } else if meta.path.is_ident("auto_increment") {
                let span = meta.path.span();
                let lit = meta.value()?.parse()?;
                if let Lit::Bool(litbool) = lit {
                    *auto_increment = litbool.value();
                    parsed.auto_increment = Some((litbool.value(), span));
                } else {
                    return Err(meta.error(format!("Invalid auto_increment = {:?}", lit)));
                }
            } else if meta.path.is_ident("identity") || meta.path.is_ident("identity_by_default") {
                if parsed.identity.is_some() {
                    return Err(meta.error(
                        "a column is generated one way: `identity` or \
                         `identity_by_default`, not both",
                    ));
                }
                let identity = if meta.path.is_ident("identity") {
                    Identity::Always
                } else {
                    Identity::ByDefault
                };
                parsed.identity = Some((identity, meta.path.span()));
            } else if meta.path.is_ident("generated_stored")
                || meta.path.is_ident("generated_virtual")
            {
                if parsed.generated.is_some() {
                    return Err(meta.error(
                        "a column is generated one way: `generated_stored` or \
                         `generated_virtual`, once",
                    ));
                }
                let kind = if meta.path.is_ident("generated_stored") {
                    Generated::Stored
                } else {
                    Generated::Virtual
                };
                let span = meta.path.span();
                let key = if kind == Generated::Stored {
                    "generated_stored"
                } else {
                    "generated_virtual"
                };
                parsed.generated = Some((kind, bare_code(&meta, key)?, span));
            } else if meta.path.is_ident("comment") {
                parsed.comment = Some(meta.value()?.parse::<Lit>()?);
            } else if meta.path.is_ident("default_value") {
                parsed.default_value = Some(meta.value()?.parse::<Expr>()?);
            } else if meta.path.is_ident("default_expr") {
                parsed.default_expr = Some(bare_code(&meta, "default_expr")?);
            } else if meta.path.is_ident("column_name") {
                let lit = meta.value()?.parse()?;
                if let Lit::Str(litstr) = lit {
                    parsed.column_name = Some(litstr.value());
                } else {
                    return Err(meta.error(format!("Invalid column_name {:?}", lit)));
                }
            } else if meta.path.is_ident("variant") {
                parsed.variant = Some(bare_code(&meta, "variant")?);
            } else if meta.path.is_ident("enum_name") {
                return Err(unread_model_field_key(&meta));
            } else if meta.path.is_ident("select_as") || meta.path.is_ident("select_with") {
                parsed.select = Some(conversion(&meta, &parsed.select, READ)?);
            } else if meta.path.is_ident("save_as") || meta.path.is_ident("save_with") {
                parsed.save = Some(conversion(&meta, &parsed.save, WRITE)?);
            } else if meta.path.is_ident("save_array_with") {
                parsed.save_array_with =
                    Some((bare_code(&meta, "save_array_with")?, meta.path.span()));
            } else if meta.path.is_ident("ignore") {
                parsed.ignore = true;
            } else if meta.path.is_ident("primary_key") {
                if parsed.primary_key.is_some() {
                    return Err(meta
                        .error("a field is one column of the key; `primary_key` is given twice"));
                }
                parsed.primary_key = Some(meta.path.span());
                primary_key_types.push(field.ty.clone());
            } else if meta.path.is_ident("without_overlaps") {
                parsed.without_overlaps = Some(meta.path.span());
            } else if meta.path.is_ident("nullable") {
                parsed.nullable = true;
            } else if meta.path.is_ident("indexed") {
                parsed.indexed = true;
            } else if meta.path.is_ident("unique") {
                parsed.unique = true;
            } else {
                return Err(unknown_pgorm_key(&meta));
            }

            Ok(())
        })?;
    }

    Ok(parsed)
}

/// Refuse an identity beside anything else that would fill the column or let
/// it be `NULL`, each a definition PostgreSQL rejects (42601).
// [spec:pgorm:sem:macros.derive.entity-model.primary-key+7]
fn check_identity(attrs: &FieldAttrs, optional: bool) -> syn::Result<()> {
    let Some((_, span)) = attrs.identity else {
        return Ok(());
    };
    let conflict = if attrs.auto_increment.is_some() {
        "an identity column already says how it is generated; drop `auto_increment`"
    } else if attrs.default_value.is_some() || attrs.default_expr.is_some() {
        "a column takes a default or an identity, not both; PostgreSQL refuses the pair"
    } else if attrs.nullable || optional {
        "an identity column is never NULL; declare the field without `Option` or `nullable`"
    } else {
        return Ok(());
    };
    Err(syn::Error::new(span, conflict))
}

/// The `without_overlaps()` a temporal key declares, from where each key
/// column wrote `without_overlaps`: nothing for a plain key. PostgreSQL takes
/// `WITHOUT OVERLAPS` on the key's last column alone and refuses a key it is
/// the only column of (both 42601), so the period is the last key field of
/// several, and anything else is refused at its key.
// [spec:pgorm:sem:macros.derive.entity-model.primary-key+7]
fn temporal_key(key_periods: &[Option<Span>]) -> syn::Result<TokenStream> {
    let last = key_periods.len().saturating_sub(1);
    if let Some(span) = key_periods[..last].iter().flatten().next() {
        return Err(syn::Error::new(
            *span,
            "`without_overlaps` marks the key's last column, its period; \
             declare this field after the key's other columns",
        ));
    }
    match key_periods.last() {
        Some(Some(span)) if key_periods.len() == 1 => Err(syn::Error::new(
            *span,
            "a WITHOUT OVERLAPS key needs a column besides its period; \
             PostgreSQL refuses a key the period is the only column of",
        )),
        Some(Some(_)) => Ok(quote! {
            fn without_overlaps() -> bool {
                true
            }
        }),
        _ => Ok(TokenStream::new()),
    }
}

/// Refuse a generated column beside anything else that would fill it, and a
/// virtual one where PostgreSQL cannot index it: the first are definitions it
/// rejects as conflicting (42601), the second as unsupported (0A000).
// [spec:pgorm:sem:macros.derive.entity-model.column-def+10]
fn check_generated(attrs: &FieldAttrs) -> syn::Result<()> {
    let Some((kind, _, span)) = &attrs.generated else {
        return Ok(());
    };
    let conflict = if attrs.identity.is_some() {
        "a column takes an identity or a generation expression, not both; PostgreSQL refuses the pair"
    } else if attrs.default_value.is_some() || attrs.default_expr.is_some() {
        "a column takes a default or a generation expression, not both; PostgreSQL refuses the pair"
    } else if attrs.auto_increment.is_some() {
        "a generated column already says how it is filled; drop `auto_increment`"
    } else if *kind == Generated::Virtual
        && (attrs.primary_key.is_some() || attrs.unique || attrs.indexed)
    {
        "a VIRTUAL generated column cannot be keyed or indexed, which PostgreSQL does not \
         support; declare it `generated_stored`"
    } else {
        return Ok(());
    };
    Err(syn::Error::new(*span, conflict))
}

/// Advances past whatever an unrecognised `#[serde(..)]` parameter carries —
/// `= expr`, a parenthesised group, or nothing — so that reading the two
/// parameters that name JSON keys does not fail on the rest.
fn skip_serde_meta(meta: &ParseNestedMeta) -> syn::Result<()> {
    if meta.input.peek(Token![=]) {
        let _: Option<Expr> = meta.value().and_then(|value| value.parse()).ok();
    } else if meta.input.peek(Paren) {
        let group;
        parenthesized!(group in meta.input);
        let _: TokenStream = group.parse()?;
    }
    Ok(())
}

/// The literal a `serde` renaming parameter carries. `serde` admits both the
/// single `= "..."` form and the split `(serialize = "..", deserialize = "..")`
/// one; only the deserialize half names the key a JSON object is read by, so the
/// split form's serialize half is discarded.
fn serde_rename_literal(meta: &ParseNestedMeta) -> syn::Result<Option<LitStr>> {
    if !meta.input.peek(Paren) {
        return Ok(Some(meta.value()?.parse()?));
    }

    let group;
    parenthesized!(group in meta.input);
    let mut deserialize = None;
    while !group.is_empty() {
        let key: Ident = group.parse()?;
        group.parse::<Token![=]>()?;
        let value: LitStr = group.parse()?;
        if key == "deserialize" {
            deserialize = Some(value);
        }
        if !group.is_empty() {
            group.parse::<Token![,]>()?;
        }
    }
    Ok(deserialize)
}

/// The `serde` case rule renaming every field of the model, from
/// `#[serde(rename_all = "..")]`.
fn serde_rename_all(attrs: &[Attribute]) -> syn::Result<Option<CaseStyle>> {
    let mut rule = None;
    for attr in attrs.iter().filter(|attr| attr.path().is_ident("serde")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                if let Some(literal) = serde_rename_literal(&meta)? {
                    let value = literal.value();
                    rule = Some(CaseStyle::from_str(&value).map_err(|()| {
                        syn::Error::new_spanned(
                            &literal,
                            format!("unsupported `serde(rename_all)` case style: `{value}`"),
                        )
                    })?);
                }
            } else {
                skip_serde_meta(&meta)?;
            }
            Ok(())
        })?;
    }
    Ok(rule)
}

/// The `serde` key one field is renamed to, from `#[serde(rename = "..")]`.
fn serde_field_rename(attrs: &[Attribute]) -> syn::Result<Option<String>> {
    let mut rename = None;
    for attr in attrs.iter().filter(|attr| attr.path().is_ident("serde")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename") {
                if let Some(literal) = serde_rename_literal(&meta)? {
                    rename = Some(literal.value());
                }
            } else {
                skip_serde_meta(&meta)?;
            }
            Ok(())
        })?;
    }
    Ok(rename)
}

/// Method to derive an Model
// [spec:pgorm:sem:macros.derive.entity-model+8]
// [spec:pgorm:syn:macros.derive.entity-model.attrs+7]
// [spec:pgorm:sem:macros.derive.entity-model.casing+4]
// [spec:pgorm:sem:macros.derive.entity-model.column-def+10]
// [spec:pgorm:sem:macros.derive.entity-model.primary-key+7]
pub fn expand_derive_entity_model(
    model: &Ident,
    data: Data,
    attrs: Vec<Attribute>,
) -> syn::Result<TokenStream> {
    // if #[pgorm(table_name = "foo", schema_name = "bar")] specified, create Entity struct
    let mut table_name = None;
    let mut comment = quote! {None};
    let mut schema_name = quote! { None };
    let mut table_iden = false;
    let mut rename_all: Option<CaseStyle> = None;

    attrs
        .iter()
        .filter(|attr| attr.path().is_ident("pgorm"))
        .try_for_each(|attr| {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("comment") {
                    let name: Lit = meta.value()?.parse()?;
                    comment = quote! { Some(#name) };
                } else if meta.path.is_ident("table_name") {
                    table_name = Some(meta.value()?.parse::<Lit>()?);
                } else if meta.path.is_ident("schema_name") {
                    let name: Lit = meta.value()?.parse()?;
                    schema_name = quote! { Some(#name) };
                } else if meta.path.is_ident("table_iden") {
                    table_iden = true;
                } else if meta.path.is_ident("rename_all") {
                    rename_all = Some((&meta).try_into()?);
                } else {
                    return Err(unknown_pgorm_key(&meta));
                }

                Ok(())
            })
        })?;

    let entity_def = table_name
        .as_ref()
        .map(|table_name| {
            quote! {
                #[doc = " Generated by pgorm-macros"]
                #[derive(Copy, Clone, Default, Debug, pgorm::prelude::EntityTrait)]
                pub struct Entity;

                #[automatically_derived]
                impl pgorm::prelude::EntityName for Entity {
                    fn schema_name(&self) -> Option<&str> {
                        #schema_name
                    }

                    fn table_name(&self) -> &str {
                        #table_name
                    }

                    fn comment(&self) -> Option<&str> {
                        #comment
                    }
                }
            }
        })
        .unwrap_or_default();

    let serde_rename_all = serde_rename_all(&attrs)?;

    // generate Column enum and it's ColumnTrait impl
    let mut columns_enum: Punctuated<_, Comma> = Punctuated::new();
    let mut columns_trait: Punctuated<_, Comma> = Punctuated::new();
    let mut columns_json_key: Punctuated<_, Comma> = Punctuated::new();
    let mut columns_select_as: Punctuated<_, Comma> = Punctuated::new();
    let mut columns_save_as: Punctuated<_, Comma> = Punctuated::new();
    let mut columns_save_array_as: Punctuated<_, Comma> = Punctuated::new();
    let mut primary_keys: Vec<(Ident, String)> = Vec::new();
    let mut primary_key_types: Punctuated<Type, Comma> = Punctuated::new();
    let mut auto_increment = true;
    let mut key_generated: Vec<bool> = Vec::new();
    let mut key_spans: Vec<Span> = Vec::new();
    let mut key_periods: Vec<Option<Span>> = Vec::new();
    let mut serial_key_fields: Vec<Span> = Vec::new();
    if table_iden && table_name.is_some() {
        let table_field_name = Ident::new("Table", Span::call_site());
        columns_enum.push(quote! {
            #[doc = " Generated by pgorm-macros"]
            #[strum(disabled)]
            #table_field_name
        });
        columns_trait
            .push(quote! { Self::#table_field_name => panic!("Table cannot be used as a column") });
        columns_json_key
            .push(quote! { Self::#table_field_name => panic!("Table cannot be used as a column") });
    }
    if let Data::Struct(item_struct) = data
        && let Fields::Named(fields) = item_struct.fields
    {
        for field in fields.named {
            if let Some(ident) = &field.ident {
                let original_field_name = trim_starting_raw_identifier(ident);
                let mut field_name =
                    column_variant_ident(&original_field_name.to_upper_camel_case(), ident)?;

                let derived_column_name = if let Some(case_style) = rename_all {
                    Some(field_name.convert_case(Some(case_style)))
                } else if original_field_name
                    != original_field_name.to_upper_camel_case().to_snake_case()
                {
                    // `to_snake_case` was used to trim prefix and tailing underscore
                    Some(original_field_name.to_snake_case())
                } else {
                    None
                };

                let attrs = parse_field_attrs(
                    &field,
                    derived_column_name,
                    &mut auto_increment,
                    &mut primary_key_types,
                )?;
                check_identity(&attrs, unwrap_option(&field.ty).is_some())?;
                check_generated(&attrs)?;
                let FieldAttrs {
                    sql_type,
                    column_name,
                    variant,
                    comment,
                    default_value,
                    default_expr,
                    select,
                    save,
                    save_array_with,
                    primary_key,
                    without_overlaps,
                    mut nullable,
                    indexed,
                    unique,
                    ignore,
                    auto_increment: field_auto_increment,
                    identity,
                    generated,
                } = attrs;

                if let Some(variant) = variant {
                    field_name = variant;
                }

                field_name = parse_derived_ident(&escape_rust_keyword(&field_name), ident)?;

                let variant_attrs = match &column_name {
                    Some(column_name) => quote! {
                        #[pgorm(column_name = #column_name)]
                        #[doc = " Generated by pgorm-macros"]
                    },
                    None => quote! {
                        #[doc = " Generated by pgorm-macros"]
                    },
                };

                if ignore {
                    continue;
                } else {
                    columns_enum.push(quote! {
                        #variant_attrs
                        #field_name
                    });
                    let json_key = match serde_field_rename(&field.attrs)? {
                        Some(rename) => rename,
                        None => convert_case_str(&original_field_name, serde_rename_all),
                    };
                    columns_json_key.push(quote! { Self::#field_name => #json_key });
                }

                if let (Some(span), None) = (without_overlaps, primary_key) {
                    return Err(syn::Error::new(
                        span,
                        "`without_overlaps` marks the period of a temporal primary key; \
                         declare the field `primary_key` too",
                    ));
                }
                if let Some(span) = primary_key {
                    key_spans.push(span);
                    key_periods.push(without_overlaps);
                    let key_name = column_name
                        .clone()
                        .unwrap_or_else(|| field_name.to_string().to_snake_case());
                    primary_keys.push((field_name.clone(), key_name));
                    key_generated.push(identity.is_some() || generated.is_some());
                    if let Some((true, span)) = field_auto_increment {
                        serial_key_fields.push(span);
                    }
                }

                let (read, written) = conversion_arms(select, save, save_array_with)?;
                if let Some(read) = read {
                    columns_select_as.push(quote! { Self::#field_name => #read });
                }
                if let Some(Written { value, array }) = written {
                    columns_save_as.push(quote! { Self::#field_name => #value });
                    columns_save_array_as.push(quote! { Self::#field_name => #array });
                }

                let field_type = match unwrap_option(&field.ty) {
                    Some(inner) => {
                        nullable = true;
                        inner
                    }
                    None => &field.ty,
                };
                let field_span = field.span();

                let pgorm_query_col_type = crate::derives::sql_type_match::col_type_match(
                    sql_type, field_type, field_span,
                )?;

                let col_def =
                    quote! { pgorm::prelude::ColumnTypeTrait::def(#pgorm_query_col_type) };

                let mut match_row = quote! { Self::#field_name => #col_def };
                if nullable {
                    match_row = quote! { #match_row.nullable() };
                }
                if indexed {
                    match_row = quote! { #match_row.indexed() };
                }
                if unique {
                    match_row = quote! { #match_row.unique() };
                }
                if let Some(default_value) = default_value {
                    match_row = quote! { #match_row.default_value(#default_value) };
                }
                if let Some(comment) = comment {
                    match_row = quote! { #match_row.comment(#comment) };
                }
                if let Some(default_expr) = default_expr {
                    match_row = quote! { #match_row.default(#default_expr) };
                }
                if let Some((identity, _)) = identity {
                    let builder = identity.builder();
                    match_row = quote! { #match_row #builder };
                }
                if let Some((kind, expr, _)) = generated {
                    let builder = kind.builder(&expr);
                    match_row = quote! { #match_row #builder };
                }
                columns_trait.push(match_row);
            }
        }
    }

    // Add tailing comma
    if !columns_select_as.is_empty() {
        columns_select_as.push_punct(Comma::default());
    }
    if !columns_save_as.is_empty() {
        columns_save_as.push_punct(Comma::default());
    }
    if !columns_save_array_as.is_empty() {
        columns_save_array_as.push_punct(Comma::default());
    }

    if primary_keys.is_empty() {
        return Err(syn::Error::new(
            model.span(),
            "Entity must have a primary key column. \
             See <https://github.com/pgorm-rs/pgorm/issues/485> for details.",
        ));
    }

    if let Some(span) = key_spans.get(MAX_KEY_ARITY) {
        return Err(syn::Error::new(
            *span,
            format!(
                "a primary key has at most {MAX_KEY_ARITY} columns, the widest tuple a key \
                 value can be; this is column {} of {}",
                MAX_KEY_ARITY + 1,
                key_spans.len(),
            ),
        ));
    }

    if primary_keys.len() > 1
        && let Some(span) = serial_key_fields.first()
    {
        return Err(syn::Error::new(
            *span,
            "a composite primary key is not drawn from the serial family; \
             declare its generated column `identity` instead",
        ));
    }

    let without_overlaps = temporal_key(&key_periods)?;
    let primary_key = {
        // The database generates the whole key: every key column is an
        // identity or a generated column, or the key is one column the serial
        // family fills.
        let auto_increment = if key_generated.contains(&true) {
            !key_generated.contains(&false)
        } else {
            auto_increment && primary_keys.len() == 1
        };
        let primary_key_types = if primary_key_types.len() == 1 {
            let first = primary_key_types.first();
            quote! { #first }
        } else {
            quote! { (#primary_key_types) }
        };
        let key_variants = primary_keys.iter().map(|(variant, _)| variant);
        let key_impls = expand_primary_key(&primary_keys);
        quote! {
            #[doc = " Generated by pgorm-macros"]
            #[derive(Copy, Clone, Debug, pgorm::prelude::EnumIter)]
            pub enum PrimaryKey {
                #(
                    #[doc = " Generated by pgorm-macros"]
                    #key_variants,
                )*
            }

            #key_impls

            #[automatically_derived]
            impl pgorm::prelude::PrimaryKeyTrait for PrimaryKey {
                type ValueType = #primary_key_types;

                fn auto_increment() -> bool {
                    #auto_increment
                }

                #without_overlaps
            }
        }
    };

    Ok(quote! {
        #[doc = " Generated by pgorm-macros"]
        #[derive(Copy, Clone, Debug, pgorm::prelude::EnumIter, pgorm::prelude::Column)]
        pub enum Column {
            #columns_enum
        }

        #[automatically_derived]
        impl pgorm::prelude::ColumnTrait for Column {
            type EntityName = Entity;

            fn def(&self) -> pgorm::prelude::ColumnDef {
                match self {
                    #columns_trait
                }
            }

            fn json_key(&self) -> &str {
                match self {
                    #columns_json_key
                }
            }

            fn select_as(&self, expr: pgorm::pgorm_query::Expr) -> pgorm::pgorm_query::SimpleExpr {
                match self {
                    #columns_select_as
                    _ => pgorm::prelude::ColumnTrait::select_enum_as(self, expr),
                }
            }

            fn save_as(&self, val: pgorm::pgorm_query::Expr) -> pgorm::pgorm_query::SimpleExpr {
                match self {
                    #columns_save_as
                    _ => pgorm::prelude::ColumnTrait::save_enum_as(self, val),
                }
            }

            fn save_array_as(&self, val: pgorm::pgorm_query::Expr) -> pgorm::pgorm_query::SimpleExpr {
                match self {
                    #columns_save_array_as
                    _ => pgorm::prelude::ColumnTrait::save_enum_array_as(self, val),
                }
            }
        }

        #entity_def

        #primary_key
    })
}

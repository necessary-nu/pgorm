use super::util::{Reader, field_not_ignored, field_variant, format_field_ident};
use proc_macro2::{Ident, TokenStream};
use quote::{quote, quote_spanned};
use syn::{Data, DataStruct, Field, Fields, Type, punctuated::IntoIter};

/// The `ActiveModel` the composite derive writes beside its `Model`, and its
/// `ActiveModelBehavior` with no hooks unless the program writes its own.
// [spec:pgorm:sem:macros.derive.active-model+7]
// [spec:pgorm:sem:macros.derive.boilerplate]
// [spec:pgorm:syn:macros.derive.entity-model.attrs+10]    the field-key vocabulary this
// expansion shares with the `Entity` derive
pub fn expand_active_model(ident: Ident, data: Data, hooks: bool) -> syn::Result<TokenStream> {
    // including ignored fields
    let all_fields = match data {
        Data::Struct(DataStruct {
            fields: Fields::Named(named),
            ..
        }) => named.named,
        _ => {
            return Ok(quote_spanned! {
                ident.span() => compile_error!("an ActiveModel is written for a struct");
            });
        }
    }
    .into_iter();

    let derive_active_model = derive_active_model(all_fields.clone())?;
    let derive_into_model = derive_into_model(all_fields)?;
    let behaviour = (!hooks).then(|| {
        quote! {
            #[automatically_derived]
            impl pgorm::ActiveModelBehavior for ActiveModel {}
        }
    });

    Ok(quote!(
        #derive_active_model
        #derive_into_model
        #behaviour
    ))
}

fn derive_active_model(all_fields: IntoIter<Field>) -> syn::Result<TokenStream> {
    let fields = all_fields.filter(field_not_ignored);

    let field: Vec<Ident> = fields.clone().map(format_field_ident).collect();

    let name: Vec<Ident> = fields
        .clone()
        .map(|field| field_variant(&field, Reader::Composite))
        .collect::<syn::Result<_>>()?;

    let ty: Vec<Type> = fields.into_iter().map(|Field { ty, .. }| ty).collect();

    let mismatch_msg: Vec<String> = field
        .iter()
        .map(|field| format!("value does not match the type of ActiveModel field {field}"))
        .collect();

    // One spelling for the one failure `take`, `get` and `set` share: the
    // column is not this ActiveModel's.
    let missing_msg = "This ActiveModel does not have this field";

    Ok(quote!(
        #[doc = " Generated by pgorm-macros"]
        #[derive(Clone, Debug, PartialEq)]
        pub struct ActiveModel {

            #(
                #[doc = " Generated by pgorm-macros"]
                pub #field: pgorm::ActiveValue<#ty>
            ),*
        }

        #[automatically_derived]
        impl std::default::Default for ActiveModel {
            fn default() -> Self {
                <Self as pgorm::ActiveModelBehavior>::new()
            }
        }

        #[automatically_derived]
        impl std::convert::From<<Entity as pgorm::EntityTrait>::Model> for ActiveModel {
            fn from(m: <Entity as pgorm::EntityTrait>::Model) -> Self {
                Self {
                    #(#field: pgorm::ActiveValue::unchanged(m.#field)),*
                }
            }
        }

        #[automatically_derived]
        impl pgorm::IntoActiveModel<ActiveModel> for <Entity as pgorm::EntityTrait>::Model {
            fn into_active_model(self) -> ActiveModel {
                self.into()
            }
        }

        #[automatically_derived]
        impl pgorm::ActiveModelTrait for ActiveModel {
            type Entity = Entity;

            fn take(&mut self, c: <Self::Entity as pgorm::EntityTrait>::Column) -> std::result::Result<pgorm::ActiveValue<pgorm::Value>, pgorm::Error> {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => {
                        let mut value = pgorm::ActiveValue::not_set();
                        std::mem::swap(&mut value, &mut self.#field);
                        Ok(value.into_wrapped_value())
                    },)*
                    _ => Err(pgorm::Error::Type(#missing_msg.to_owned())),
                }
            }

            fn get(&self, c: <Self::Entity as pgorm::EntityTrait>::Column) -> std::result::Result<pgorm::ActiveValue<pgorm::Value>, pgorm::Error> {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => Ok(self.#field.clone().into_wrapped_value()),)*
                    _ => Err(pgorm::Error::Type(#missing_msg.to_owned())),
                }
            }

            fn set(&mut self, c: <Self::Entity as pgorm::EntityTrait>::Column, v: pgorm::Value) -> std::result::Result<(), pgorm::Error> {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => {
                        self.#field = pgorm::ActiveValue::set(
                            pgorm::pgorm_query::ValueType::try_from(v)
                                .map_err(|_| pgorm::Error::Type(#mismatch_msg.to_owned()))?,
                        );
                        Ok(())
                    },)*
                    _ => Err(pgorm::Error::Type(#missing_msg.to_owned())),
                }
            }

            fn not_set(&mut self, c: <Self::Entity as pgorm::EntityTrait>::Column) {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => self.#field = pgorm::ActiveValue::not_set(),)*
                    _ => {},
                }
            }

            fn is_not_set(&self, c: <Self::Entity as pgorm::EntityTrait>::Column) -> bool {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => self.#field.is_not_set(),)*
                    _ => panic!("This ActiveModel does not have this field"),
                }
            }

            fn default() -> Self {
                Self {
                    #(#field: pgorm::ActiveValue::not_set()),*
                }
            }

            fn reset(&mut self, c: <Self::Entity as pgorm::EntityTrait>::Column) {
                match c {
                    #(<Self::Entity as pgorm::EntityTrait>::Column::#name => self.#field.reset(),)*
                    _ => panic!("This ActiveModel does not have this field"),
                }
            }
        }
    ))
}

fn derive_into_model(model_fields: IntoIter<Field>) -> syn::Result<TokenStream> {
    let active_model_fields = model_fields.clone().filter(field_not_ignored);

    let active_model_field: Vec<Ident> = active_model_fields
        .into_iter()
        .map(format_field_ident)
        .collect();
    let model_field: Vec<Ident> = model_fields.clone().map(format_field_ident).collect();

    let ignore_attr: Vec<bool> = model_fields
        .map(|field| !field_not_ignored(&field))
        .collect();

    let model_field_value: Vec<TokenStream> = model_field
        .iter()
        .zip(ignore_attr)
        .map(|(field, ignore)| {
            if ignore {
                quote! {
                    Default::default()
                }
            } else {
                quote! {
                    a.#field.take().ok_or_else(|| {
                        pgorm::Error::AttrNotSet(stringify!(#field).to_owned())
                    })?
                }
            }
        })
        .collect();

    Ok(quote!(
        #[automatically_derived]
        impl std::convert::TryFrom<ActiveModel> for <Entity as pgorm::EntityTrait>::Model {
            type Error = pgorm::Error;
            fn try_from(mut a: ActiveModel) -> Result<Self, pgorm::Error> {
                #(if matches!(a.#active_model_field, pgorm::ActiveValue::NotSet) {
                    return Err(pgorm::Error::AttrNotSet(stringify!(#active_model_field).to_owned()));
                })*
                Ok(
                    Self {
                        #(#model_field: #model_field_value),*
                    }
                )
            }
        }

        #[automatically_derived]
        impl pgorm::TryIntoModel<<Entity as pgorm::EntityTrait>::Model> for ActiveModel {
            fn try_into_model(self) -> Result<<Entity as pgorm::EntityTrait>::Model, pgorm::Error> {
                self.try_into()
            }
        }
    ))
}

-- The schema the declared-model writers are held to: pgorm-codegen's tests
-- compare what each writes for it with the modules the bindings commit, and
-- each binding's suite imports its module, type-checks it and round-trips
-- rows through it on a database this text creates.

CREATE TYPE flavor AS ENUM ('chocolate', 'vanilla', 'lemon', 'carrot');

CREATE DOMAIN special_flavor AS flavor;

CREATE DOMAIN grams AS integer;

CREATE TYPE temperature AS RANGE (SUBTYPE = double precision);

CREATE TABLE bakery (
    id serial PRIMARY KEY,
    name varchar NOT NULL,
    city varchar(40)
);

CREATE TABLE cake (
    id serial PRIMARY KEY,
    name text NOT NULL,
    flavor flavor NOT NULL,
    special special_flavor,
    price numeric(10, 2) NOT NULL,
    tip money,
    gluten_free boolean NOT NULL DEFAULT false,
    bakery_id integer NOT NULL REFERENCES bakery (id) ON DELETE CASCADE
);

CREATE TABLE baker (
    id serial PRIMARY KEY,
    name text NOT NULL,
    email varchar NOT NULL UNIQUE
);

CREATE TABLE cake_baker (
    cake_id integer NOT NULL REFERENCES cake (id) ON DELETE CASCADE,
    baker_id integer NOT NULL REFERENCES baker (id) ON DELETE CASCADE,
    PRIMARY KEY (cake_id, baker_id)
);

CREATE TABLE sample (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    small smallint,
    whole integer,
    big bigint,
    single real,
    double double precision,
    amount numeric,
    price numeric(8, 3),
    tip money,
    ok boolean,
    body text,
    label varchar,
    code varchar(12),
    initials char(3),
    raw bytea,
    doc json,
    docb jsonb,
    ref uuid,
    day date,
    at_time time,
    at timestamp,
    at_utc timestamptz,
    span interval,
    short_span interval hour to minute,
    ints int4range,
    bigs int8range,
    nums numrange,
    days daterange,
    stamps tsrange,
    instants tstzrange,
    int_sets int4multirange,
    day_sets datemultirange,
    heat temperature,
    flavor flavor,
    special special_flavor,
    flavors flavor[],
    tags text[],
    counts integer[],
    weight grams,
    quantity integer NOT NULL DEFAULT 1,
    note text NOT NULL DEFAULT 'none',
    created timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    doubled integer GENERATED ALWAYS AS (quantity * 2) STORED,
    UNIQUE (label, code)
);

CREATE TYPE "public"."payment_kind" AS ENUM ('card', 'cash', 'voucher');

CREATE TABLE "payment" (
    "id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "kind" public.payment_kind NOT NULL,
    "order_id" integer NOT NULL,
    "amount" decimal NOT NULL,
    PRIMARY KEY ("id"),
    CONSTRAINT "uq-payment-id-kind" UNIQUE ("id", "kind")
);

CREATE TABLE "card_payment" (
    "payment_id" integer NOT NULL,
    "last_four" text NOT NULL,
    "kind" public.payment_kind GENERATED ALWAYS AS ('card') STORED,
    PRIMARY KEY ("payment_id"),
    CONSTRAINT "fk-card_payment-payment_id-kind" FOREIGN KEY ("payment_id", "kind")
        REFERENCES "payment" ("id", "kind") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE "voucher_payment" (
    "payment_id" integer NOT NULL,
    "code" text NOT NULL,
    "kind" public.payment_kind GENERATED ALWAYS AS ('voucher') STORED,
    PRIMARY KEY ("payment_id"),
    CONSTRAINT "fk-voucher_payment-payment_id-kind" FOREIGN KEY ("payment_id", "kind")
        REFERENCES "payment" ("id", "kind") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

ALTER TABLE "payment"
    ADD COLUMN "card_id" integer
        GENERATED ALWAYS AS ((CASE WHEN ("kind" = 'card') THEN "id" END)) STORED,
    ADD COLUMN "voucher_id" integer
        GENERATED ALWAYS AS ((CASE WHEN ("kind" = 'voucher') THEN "id" END)) STORED,
    ADD CONSTRAINT "fk-payment-card_id" FOREIGN KEY ("card_id")
        REFERENCES "card_payment" ("payment_id") DEFERRABLE INITIALLY IMMEDIATE,
    ADD CONSTRAINT "fk-payment-voucher_id" FOREIGN KEY ("voucher_id")
        REFERENCES "voucher_payment" ("payment_id") DEFERRABLE INITIALLY IMMEDIATE;

CREATE TABLE review (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stars smallint NOT NULL,
    body text NOT NULL,
    cake_id integer REFERENCES cake (id),
    bakery_id integer REFERENCES bakery (id),
    CONSTRAINT "ck-review-subject" CHECK (num_nonnulls(cake_id, bakery_id) = 1)
);

//! Generated source laid out as a person writes it, with no formatter run
//! afterwards: each block of items printed by prettyplease, the blocks
//! separated by blank lines, the functions of an `impl` too, and every
//! `#[pgorm(..)]` attribute laid out as the guide writes one.
//!
//! prettyplease prints an attribute's arguments as loose tokens, so a struct
//! literal inside one comes out as `Domain{name:Name::runtime(..)}`. An
//! attribute's arguments are expressions, though — `primary_key`,
//! `table_name = "cake"`, `unique(columns = (..))` — so each is printed as
//! the arguments of a call, which prettyplease lays out whole: on one line
//! where it fits, one argument to a line where it does not.

use proc_macro2::TokenStream;
use quote::format_ident;
use syn::{Attribute, Expr, Fields, Item, Meta, punctuated::Punctuated, token::Comma};

/// The header every generated file opens with.
// [spec:pgorm:req:codegen.entity.files+3]
pub(crate) fn header() -> String {
    format!(
        "//! `pgorm` Entity, @generated by pgorm-codegen {}",
        env!("CARGO_PKG_VERSION")
    )
}

/// A whole file: the header, then each block formatted, a blank line before
/// each, and a final newline.
// [spec:pgorm:req:codegen.entity.files+3]
pub(crate) fn file<I>(blocks: I) -> String
where
    I: IntoIterator<Item = TokenStream>,
{
    let mut out = header();
    out.push('\n');
    for block in blocks {
        let block = self::block(block);
        if !block.is_empty() {
            out.push('\n');
            out.push_str(&block);
        }
    }
    out
}

/// One block of items, formatted, ending in a newline; empty for a block
/// holding none.
fn block(tokens: TokenStream) -> String {
    let mut file: syn::File = syn::parse2(tokens).expect("the writer's blocks are Rust items");
    let mut attributes = Vec::new();
    for item in &mut file.items {
        mark_item(item, &mut attributes);
    }
    if file.items.iter().all(|item| matches!(item, Item::Use(_))) {
        return file.items.iter().map(import).collect();
    }
    let impls = file.items.iter().any(|item| matches!(item, Item::Impl(_)));
    let mut printed = String::new();
    for line in prettyplease::unparse(&file).lines() {
        let marked = line
            .trim_start()
            .strip_prefix("#[")
            .and_then(|rest| rest.strip_suffix(']'))
            .and_then(|marker| marker.strip_prefix(MARKER))
            .and_then(|index| index.parse::<usize>().ok());
        match marked {
            Some(index) => {
                let indent = line.len() - line.trim_start().len();
                printed.push_str(&attribute(&attributes[index], indent));
            }
            None => {
                if impls && separates_impl_items(&printed, line) {
                    printed.push('\n');
                }
                printed.push_str(line);
                printed.push('\n');
            }
        }
    }
    printed
}

/// A `use` on one line where it fits in rustfmt's width, which is wider than
/// the width prettyplease breaks at, so that rustfmt leaves the line as it is.
fn import(item: &Item) -> String {
    let file: syn::File = syn::parse_quote!(#item);
    let printed = prettyplease::unparse(&file);
    let line = printed
        .lines()
        .map(str::trim)
        .collect::<Vec<_>>()
        .join(" ")
        .replace("{ ", "{")
        .replace(", }", "}");
    if line.len() <= RUSTFMT_WIDTH {
        line + "\n"
    } else {
        printed
    }
}

const RUSTFMT_WIDTH: usize = 100;

/// The path a marked attribute is printed under until its own layout
/// replaces it, followed by its index among the block's attributes.
const MARKER: &str = "__pgorm_codegen_attribute_";

/// Swap each `#[pgorm(..)]` on `item`, its fields and its variants for a
/// marker, keeping the attribute's arguments in `attributes`.
fn mark_item(item: &mut Item, attributes: &mut Vec<Punctuated<Expr, Comma>>) {
    match item {
        Item::Struct(item) => {
            mark(&mut item.attrs, attributes);
            mark_fields(&mut item.fields, attributes);
        }
        Item::Enum(item) => {
            mark(&mut item.attrs, attributes);
            for variant in &mut item.variants {
                mark(&mut variant.attrs, attributes);
                mark_fields(&mut variant.fields, attributes);
            }
        }
        _ => {}
    }
}

fn mark_fields(fields: &mut Fields, attributes: &mut Vec<Punctuated<Expr, Comma>>) {
    for field in fields.iter_mut() {
        mark(&mut field.attrs, attributes);
    }
}

/// An attribute whose arguments are not all expressions is left as it is,
/// printed as prettyplease prints it.
fn mark(attrs: &mut [Attribute], attributes: &mut Vec<Punctuated<Expr, Comma>>) {
    for attr in attrs {
        let Meta::List(list) = &attr.meta else {
            continue;
        };
        if !list.path.is_ident("pgorm") {
            continue;
        }
        let Ok(arguments) = list.parse_args_with(Punctuated::<Expr, Comma>::parse_terminated)
        else {
            continue;
        };
        let marker = format_ident!("{MARKER}{}", attributes.len());
        attributes.push(arguments);
        *attr = syn::parse_quote!(#[#marker]);
    }
}

/// `#[pgorm(..)]` with `arguments`, at `indent`: the arguments printed as a
/// call's, which prettyplease breaks one to a line where they do not fit,
/// with no comma after the last, as the guide writes an attribute.
// [spec:pgorm:req:codegen.entity.files+3]
fn attribute(arguments: &Punctuated<Expr, Comma>, indent: usize) -> String {
    let arguments = arguments.iter();
    let statement: syn::File = syn::parse_quote! {
        fn attribute() {
            pgorm(#(#arguments),*);
        }
    };
    let printed = prettyplease::unparse(&statement);
    let mut lines: Vec<&str> = printed
        .lines()
        .skip(1)
        .take_while(|line| *line != "}")
        .map(|line| line.strip_prefix("    ").unwrap_or(line))
        .collect();
    let last = lines.len() - 1;
    let closing = lines[last]
        .strip_suffix(");")
        .expect("a call statement ends `);`");
    let broken = last > 0;
    let mut out = String::new();
    let pad = " ".repeat(indent);
    for (number, line) in lines.drain(..).enumerate() {
        out.push_str(&pad);
        if number == 0 {
            out.push_str("#[");
        }
        if number == last {
            out.push_str(closing);
            out.push_str(")]\n");
        } else if broken && number == last - 1 {
            out.push_str(line.strip_suffix(',').unwrap_or(line));
            out.push('\n');
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Whether `line` opens an `impl`'s item after the one that just closed, so
/// a blank line goes between them as between the functions a person writes.
fn separates_impl_items(printed: &str, line: &str) -> bool {
    printed.ends_with("\n    }\n")
        && line.starts_with("    ")
        && !line.starts_with("     ")
        && line.trim() != "}"
}

/// Hold `file`, a generated file, its header line and the blank line after it
/// aside, to the golden at `path` under the crate's root, byte for byte; with
/// `PGORM_CODEGEN_BLESS` set it is written there instead.
#[cfg(test)]
#[track_caller]
pub(crate) fn hold_golden(path: &str, file: &str) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(path);
    let body = file
        .strip_prefix(&header())
        .and_then(|rest| rest.strip_prefix("\n\n"))
        .expect("a generated file opens with its header and a blank line");
    if std::env::var_os("PGORM_CODEGEN_BLESS").is_some() {
        std::fs::write(&path, body).expect("the golden is writable");
        return;
    }
    let golden = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
    pretty_assertions::assert_eq!(golden, body, "{}", path.display());
}

#[cfg(test)]
mod tests {
    use super::*;
    use pretty_assertions::assert_eq;
    use quote::quote;

    #[test]
    fn a_short_attribute_stays_on_its_line() {
        let printed = block(quote! {
            #[derive(Clone, Debug, PartialEq, Eq, Entity)]
            #[pgorm(table_name = "cake")]
            pub struct Model {
                #[pgorm(primary_key)]
                pub id: i32,
                #[pgorm(column_type = ColumnType::Decimal(Some((10, 2))))]
                pub price: Decimal,
            }
        });
        assert_eq!(
            printed,
            "#[derive(Clone, Debug, PartialEq, Eq, Entity)]\n\
             #[pgorm(table_name = \"cake\")]\n\
             pub struct Model {\n    \
                 #[pgorm(primary_key)]\n    \
                 pub id: i32,\n    \
                 #[pgorm(column_type = ColumnType::Decimal(Some((10, 2))))]\n    \
                 pub price: Decimal,\n\
             }\n"
        );
    }

    #[test]
    fn a_long_attribute_breaks_an_argument_a_line() {
        let printed = block(quote! {
            pub enum Relation {
                #[pgorm(
                    belongs_to = super::bakery::Entity,
                    from = Column::BakeryId,
                    to = super::bakery::Column::Id,
                )]
                Bakery,
            }
        });
        assert_eq!(
            printed,
            "pub enum Relation {\n    \
                 #[pgorm(\n        \
                     belongs_to = super::bakery::Entity,\n        \
                     from = Column::BakeryId,\n        \
                     to = super::bakery::Column::Id\n    \
                 )]\n    \
                 Bakery,\n\
             }\n"
        );
    }

    #[test]
    fn a_struct_literal_attribute_reads_as_rust() {
        let printed = block(quote! {
            pub struct Model {
                #[pgorm(column_type = ColumnType::Domain { name: Name::runtime("grams"), schema: None, base: Arc::new(ColumnType::Integer) })]
                pub weight: i32,
            }
        });
        assert!(printed.contains("ColumnType::Domain {\n"), "{printed}");
        assert!(
            printed.contains("name: Name::runtime(\"grams\"),"),
            "{printed}"
        );
    }

    #[test]
    fn an_impl_separates_its_functions() {
        let printed = block(quote! {
            impl Related<super::baker::Entity> for Entity {
                fn to() -> RelationDef {
                    super::cake_baker::Relation::Baker.def()
                }
                fn via() -> Option<RelationDef> {
                    Some(super::cake_baker::Relation::Cake.def().rev())
                }
            }
        });
        assert_eq!(
            printed,
            "impl Related<super::baker::Entity> for Entity {\n    \
                 fn to() -> RelationDef {\n        \
                     super::cake_baker::Relation::Baker.def()\n    \
                 }\n\
                 \n    \
                 fn via() -> Option<RelationDef> {\n        \
                     Some(super::cake_baker::Relation::Cake.def().rev())\n    \
                 }\n\
             }\n"
        );
    }
}

// A declared model's hooks, against a live server in either runtime: they run
// around the record writes of Model.active(values), plain or returning a
// promise, a before hook's error refusing the write before anything is sent
// and an after hook's arriving once the row is written, while the statement
// builders run none.

import assert from "node:assert/strict";
import { after, before, beforeEach, test } from "node:test";

import { column, ConstructionError, DecodeError, model, ModelActive, Pool } from "../lib/index.js";
import { scratchDatabase } from "./support.ts";

const columns = {
  id: column("i32", { primaryKey: true, default: true }),
  name: column("text"),
  note: column("text"),
};

let database: { pool: Pool; drop(): Promise<void> } | undefined;

function pool(): Pool {
  if (!database) throw new Error("the scratch database was not created");
  return database.pool;
}

before(async () => {
  const scratch = await scratchDatabase("pgorm_napi_model_hooks");
  const created = new Pool(scratch.dsn, { maxSize: 2 });
  await created.execute("CREATE SCHEMA hooks");
  await created.execute(
    "CREATE TABLE hooks.special (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, note text NOT NULL)",
  );
  database = {
    pool: created,
    async drop() {
      await created.close();
      await scratch.drop();
    },
  };
});

beforeEach(async () => {
  await pool().execute("TRUNCATE hooks.special RESTART IDENTITY");
});

after(async () => {
  await database?.drop();
});

function hooked(calls: unknown[][]) {
  return model("special", {
    schema: "hooks",
    columns,
    hooks: {
      beforeSave(values, insert) {
        calls.push(["beforeSave", insert]);
        if (values.name === "") throw new Error("a special needs a name");
        return { note: "Ask at the counter", ...values };
      },
      async afterSave(record, insert) {
        calls.push(["afterSave", record.name, insert]);
        return record;
      },
      async beforeDelete(values) {
        calls.push(["beforeDelete"]);
        return values;
      },
      afterDelete() {
        calls.push(["afterDelete"]);
      },
    },
  });
}

async function count(): Promise<number> {
  const [row] = await pool().query("SELECT count(*)::int4 AS n FROM hooks.special");
  return Number(row!.n);
}

// [spec:pgorm:req:bindings.model-hooks/test]    the hooks a model takes, and what describe() says of them
test("a model takes its hooks as functions and describes which it has", () => {
  const special = model("special", { schema: "hooks", columns, hooks: { beforeSave: (values) => values } });
  assert.deepStrictEqual(special.describe().hooks, ["beforeSave"]);
  assert.deepStrictEqual(special.as("s").describe().hooks, ["beforeSave"]);
  assert.deepStrictEqual(model("special", { columns }).describe().hooks, []);
  // @ts-expect-error: beforeInsert is no model hook
  assert.throws(() => model("special", { columns, hooks: { beforeInsert: () => ({}) } }), /"beforeInsert" is no model hook/);
  // @ts-expect-error: a hook is a function
  assert.throws(() => model("special", { columns, hooks: { beforeSave: "nope" } }), /beforeSave hook is a function/);
  assert.ok(special.active({ name: "x" }) instanceof ModelActive);
  // @ts-expect-error: colour is no field of the model
  assert.throws(() => special.active({ colour: "red" }), ConstructionError);
});

// [spec:pgorm:req:bindings.model-hooks/test]
test("insert, update and delete of a record run the hooks around the write", async () => {
  const calls: unknown[][] = [];
  const special = hooked(calls);
  const saved = await special.active({ name: "Saturday buns" }).insert(pool());
  assert.deepStrictEqual([saved.name, saved.note], ["Saturday buns", "Ask at the counter"]);
  const updated = await special.active({ id: saved.id, name: "Sunday buns" }).update(pool());
  assert.deepStrictEqual([updated.name, updated.note], ["Sunday buns", "Ask at the counter"]);
  assert.equal(await special.active({ id: saved.id }).delete(pool()), 1);
  assert.deepStrictEqual(calls.map((call) => call[0]), [
    "beforeSave",
    "afterSave",
    "beforeSave",
    "afterSave",
    "beforeDelete",
    "afterDelete",
  ]);
  assert.deepStrictEqual([calls[0]![1], calls[2]![1]], [true, false]);
});

// [spec:pgorm:req:bindings.model-hooks/test]
test("a before hook's error refuses the write, and an after hook's arrives once it is written", async () => {
  const special = hooked([]);
  await assert.rejects(special.active({ name: "" }).insert(pool()), /a special needs a name/);
  assert.equal(await count(), 0);
  const loud = model("special", {
    schema: "hooks",
    columns,
    hooks: {
      afterSave() {
        throw new Error("after the write");
      },
    },
  });
  await assert.rejects(loud.active({ name: "kept", note: "n" }).insert(pool()), /after the write/);
  assert.equal(await count(), 1);
  const bad = model("special", { schema: "hooks", columns, hooks: { beforeSave: () => null as never } });
  await assert.rejects(bad.active({ name: "x", note: "n" }).insert(pool()), TypeError);
  await assert.rejects(special.active({ id: 999, name: "nobody" }).update(pool()), DecodeError);
  await assert.rejects(special.active({ name: "no key" }).delete(pool()), /needs its key/);
  const keyless = model("special", { schema: "hooks", columns: { name: column("text"), note: column("text") } });
  await assert.rejects(keyless.active({ name: "x" }).update(pool()), /declares no primary key/);
});

// [spec:pgorm:req:bindings.model-hooks/test]    the statement builders run no hook
test("the statement builders run no hook", async () => {
  const calls: unknown[][] = [];
  const special = hooked(calls);
  await special.insert({ name: "plain", note: "n" }).execute(pool());
  await special.update({ note: "m" }).allRows().execute(pool());
  await special.delete().allRows().execute(pool());
  assert.deepStrictEqual(calls, []);
});

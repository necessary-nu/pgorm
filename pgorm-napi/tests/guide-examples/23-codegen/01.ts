import assert from "node:assert/strict";
import { modelsFromSql } from "@necessary/pgorm";

export default async function example(): Promise<void> {
  const ddl = `
  CREATE TYPE flavor AS ENUM ('chocolate', 'vanilla', 'lemon', 'carrot');
  CREATE TABLE bakery (id serial PRIMARY KEY, name varchar NOT NULL, city varchar NOT NULL);
  CREATE TABLE cake (
    id serial PRIMARY KEY,
    name varchar NOT NULL,
    flavor flavor NOT NULL,
    price numeric(10, 2) NOT NULL,
    gluten_free boolean NOT NULL,
    bakery_id integer NOT NULL REFERENCES bakery (id)
  );
  `;
  const source = modelsFromSql(ddl);
  assert.ok(source.startsWith("// Declared models of a schema's tables, @generated by pgorm-codegen"));
  assert.ok(source.includes(`export const flavor = new TypeName("flavor", { schema: "public" });`));
  const cake = [
    `export const Cake = model("cake", {`,
    `  renameAll: "snake_case",`,
    `  columns: {`,
    `    id: column("i32", { primaryKey: true, autoIncrement: true }),`,
    `    name: column("text", { columnType: "varchar" }),`,
    `    flavor: column(flavor, {`,
    `      values: ["chocolate", "vanilla", "lemon", "carrot"],`,
    `    }),`,
    `    price: column("decimal", {`,
    `      columnType: new DataType("numeric", { precision: 10, scale: 2 }),`,
    `    }),`,
    `    glutenFree: column("bool"),`,
    `    bakeryId: column("i32"),`,
    `  },`,
    `});`,
  ];
  assert.ok(source.includes(cake.join("\n")));
  assert.ok(source.includes(`export const bakeryCake = Bakery.hasMany(Cake, { from: "id", to: "bakeryId" });`));
  const cakeBakery = [
    `export const cakeBakery = Cake.belongsTo(Bakery, {`,
    `  from: "bakeryId",`,
    `  to: "id",`,
    `});`,
  ];
  assert.ok(source.includes(cakeBakery.join("\n")));
}

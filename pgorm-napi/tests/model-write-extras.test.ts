// A declared model's writes beside the plain ones, against a live server in
// either runtime: try-inserts that say whether they wrote (pgorm's
// TryInsert), and updates and deletes that read another table (UPDATE ..
// FROM, DELETE .. USING).

import assert from "node:assert/strict";
import { after, before, beforeEach, test } from "node:test";

import { column, Conflict, ConstructionError, model, ModelTryInsertMany, Pool, Table } from "../lib/index.js";
import { scratchDatabase } from "./support.ts";

const Shop = model("shop", {
  schema: "wx",
  columns: {
    id: column("i32", { primaryKey: true, generated: "byDefault" }),
    name: column("text"),
    city: column("text"),
  },
});
const Item = model("item", {
  schema: "wx",
  columns: { id: column("i32", { primaryKey: true }), shopId: column("i32", { name: "shop_id" }), price: column("i32") },
});
const Stock = model("stock", {
  schema: "wx",
  columns: {
    shopId: column("i32", { name: "shop_id", primaryKey: true }),
    itemId: column("i32", { name: "item_id", primaryKey: true }),
  },
});
const Note = model("note", { schema: "wx", columns: { body: column("text") } });
const Tally = model("tally", { schema: "wx", columns: { id: column("i32", { primaryKey: true, generated: "byDefault" }) } });

const SCHEMA = [
  "CREATE SCHEMA wx",
  "CREATE TABLE wx.shop (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, city text NOT NULL)",
  "CREATE TABLE wx.item (id int4 PRIMARY KEY, shop_id int4 NOT NULL, price int4 NOT NULL)",
  "CREATE TABLE wx.stock (shop_id int4, item_id int4, PRIMARY KEY (shop_id, item_id))",
  "CREATE TABLE wx.note (body text NOT NULL UNIQUE)",
  "CREATE TABLE wx.tally (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
];

let database: { pool: Pool; drop(): Promise<void> } | undefined;

function pool(): Pool {
  if (!database) throw new Error("the scratch database was not created");
  return database.pool;
}

before(async () => {
  const scratch = await scratchDatabase("pgorm_napi_write_extras");
  const created = new Pool(scratch.dsn, { maxSize: 2 });
  for (const sql of SCHEMA) await created.execute(sql);
  database = {
    pool: created,
    async drop() {
      await created.close();
      await scratch.drop();
    },
  };
});

beforeEach(async () => {
  await pool().execute("TRUNCATE wx.shop, wx.item, wx.stock, wx.note, wx.tally RESTART IDENTITY");
  await Shop.insertMany([{ name: "North", city: "Oslo" }, { name: "West", city: "Bergen" }]).execute(pool());
  await Item.insertMany([{ id: 1, shopId: 1, price: 10 }, { id: 2, shopId: 1, price: 20 }, { id: 3, shopId: 2, price: 30 }]).execute(pool());
  await Stock.insert({ shopId: 1, itemId: 1 }).execute(pool());
});

after(async () => {
  await database?.drop();
});

// [spec:pgorm:req:bindings.model-try-inserts/test]    the conflict clause on the key, or on any key without one
test("a try-insert's conflict clause names the primary key, or any key for a model without one", () => {
  assert.equal(
    Stock.insert({ shopId: 1, itemId: 2 }).onConflictDoNothing().inspect().sql,
    `INSERT INTO "wx"."stock" ("shop_id", "item_id") VALUES ($1, $2) ON CONFLICT ("shop_id", "item_id") DO NOTHING`,
  );
  assert.ok(Note.insert({ body: "x" }).onConflictDoNothing().inspect().sql.endsWith("ON CONFLICT DO NOTHING"));
  assert.doesNotMatch(Stock.insert({ shopId: 1, itemId: 2 }).onEmptyDoNothing().inspect().sql, /ON CONFLICT/);
  const batch = Stock.insert({ shopId: 1, itemId: 2 }).onConflictDoNothing().add({ shopId: 1, itemId: 3 });
  assert.ok(batch instanceof ModelTryInsertMany);
  assert.match(batch.inspect().sql, /VALUES \(\$1, \$2\), \(\$3, \$4\) ON CONFLICT/);
  assert.throws(() => Stock.insertMany([]).onConflictDoNothing().inspect(), ConstructionError);
  // @ts-expect-error: a try-insert of one row reads its row with one, not all
  assert.throws(() => Stock.insert({ shopId: 1, itemId: 2 }).onConflictDoNothing().returning().all(pool()));
});

// [spec:pgorm:req:bindings.model-try-inserts/test]    inserted, conflicted or empty, as TryInsertResult answers
test("a try-insert says whether it wrote, its conflict skipped every row, or it had nothing to write", async () => {
  assert.deepEqual(await Stock.insert({ shopId: 1, itemId: 1 }).onConflictDoNothing().execute(pool()), { kind: "conflicted" });
  assert.deepEqual(await Stock.insert({ shopId: 1, itemId: 2 }).onConflictDoNothing().execute(pool()), { kind: "inserted", value: 1 });
  const mixed = Stock.insertMany([{ shopId: 1, itemId: 2 }, { shopId: 2, itemId: 3 }]).onConflictDoNothing();
  assert.deepEqual(await mixed.execute(pool()), { kind: "inserted", value: 1 });
  assert.deepEqual(await mixed.execute(pool()), { kind: "conflicted" });
  assert.deepEqual(await Stock.insertMany([]).onConflictDoNothing().execute(pool()), { kind: "empty" });
  assert.deepEqual(await Stock.insertMany([]).onEmptyDoNothing().execute(pool()), { kind: "empty" });
  // A row that sets no field is empty, and no row of defaults is written.
  assert.deepEqual(await Tally.insert({}).onEmptyDoNothing().execute(pool()), { kind: "empty" });
  assert.equal(await Tally.find().count(pool()), 0);
  // An insert of no rows takes a conflict clause and still sends nothing.
  assert.equal(await Stock.insertMany([]).onConflict(Conflict.doNothing()).execute(pool()), 0);
});

// [spec:pgorm:req:bindings.model-try-inserts/test]    RETURNING answers with the rows written
test("a try-insert's RETURNING answers with the rows it wrote", async () => {
  assert.deepEqual(await Shop.insert({ id: 1, name: "North", city: "Oslo" }).onConflictDoNothing().returning("name").one(pool()), {
    kind: "conflicted",
  });
  const east = await Shop.insert({ name: "East", city: "Tromsø" }).onConflictDoNothing().returning().one(pool());
  assert.equal(east.kind, "inserted");
  if (east.kind === "inserted") assert.deepEqual([east.value.id, east.value.name], [3, "East"]);
  const batch = Stock.insertMany([{ shopId: 1, itemId: 1 }, { shopId: 1, itemId: 3 }]).onConflictDoNothing();
  assert.deepEqual(await batch.returning().all(pool()), { kind: "inserted", value: [{ shopId: 1, itemId: 3 }] });
  assert.deepEqual(await batch.returning().all(pool()), { kind: "conflicted" });
  assert.deepEqual(await Stock.insertMany([]).onEmptyDoNothing().returning().all(pool()), { kind: "empty" });
});

// [spec:pgorm:req:bindings.model-write-sources/test]    FROM and USING name another model's table or a FROM item
test("an update reads another table through from, a delete through using", async () => {
  const raised = Item.update({ price: Item.col("price").add(1) })
    .from(Shop)
    .where(Item.col("shopId").eq(Shop.col("id")))
    .where(Shop.col("city").eq("Oslo"));
  assert.equal(
    raised.inspect().sql,
    `UPDATE "wx"."item" SET "price" = "item"."price" + $1 FROM "wx"."shop" WHERE "item"."shop_id" = "shop"."id" AND "shop"."city" = $2`,
  );
  assert.equal(await raised.execute(pool()), 2);
  assert.deepEqual((await Item.select("price").orderBy(Item.col("id").asc()).all(pool())).map((row) => row.price), [11, 21, 30]);
  const s = Shop.as("s");
  const gone = Item.delete().using(s).where(Item.col("shopId").eq(s.col("id"))).where(s.col("city").eq("Bergen"));
  assert.match(gone.inspect().sql, /^DELETE FROM "wx"\."item" USING "wx"\."shop" AS "s" WHERE/);
  assert.ok(gone.returning("id").inspect().sql.endsWith(`RETURNING "item"."id"`));
  assert.deepEqual((await gone.returning("id").all(pool())).map((row) => row.id), [3]);
  assert.match(Item.delete().using(new Table("elsewhere")).allRows().inspect().sql, /USING "elsewhere"/);
  // @ts-expect-error: a write reads a model, a table or a FROM item
  assert.throws(() => Item.update({ price: 1 }).from("shop"), TypeError);
});
